## Discussion

### Why Faster Is Sometimes Worse

**Scenario Analysis:**

1. **The Speed Trap**
   - Case: Optimize for fastest transit time
   - Reality: Fast routes have high variance
   - Outcome: Unpredictable deliveries, poor planning
   - Lesson: Consistency beats speed

2. **The Cost Blindness**
   - Case: Measure route cost only
   - Reality: Fast routes have high delay costs
   - Outcome: High total cost despite low route cost
   - Lesson: Total cost matters more than route cost

3. **The Metric Misalignment**
   - Case: Optimize for average transit time
   - Reality: Customers care about on-time delivery
   - Outcome: Good average, poor customer satisfaction
   - Lesson: Metrics must align with outcomes

**Discussion Questions:**
- When have you seen wrong metrics lead to wrong decisions?
- What outcomes were actually important?
- What was the actual cost of metric misalignment?
- How could better metrics have helped?

