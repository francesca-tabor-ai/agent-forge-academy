## Practical Exercise

### Design a KPI Framework for Logistics Performance

**Objective:** Build metrics that drive the right decisions

**Steps:**

1. **Define Outcome Goals**
   - Customer satisfaction: on-time, in-full delivery
   - Cost efficiency: minimize total cost-to-serve
   - Reliability: consistent performance
   - Resilience: ability to handle disruptions

2. **Design Primary Metrics**
   - OTIF: on-time-in-full percentage
   - Cost-to-serve: total cost per order
   - Transit time variance: standard deviation of delivery times
   - Resilience score: recovery time + disruption impact

3. **Design Leading Indicators**
   - Port congestion index: early warning of delays
   - Carrier performance trends: predict reliability
   - Weather severity: predict disruption risk
   - Network utilization: predict capacity constraints

4. **Define Metric Targets**
   - OTIF: >95% target
   - Cost-to-serve: <$2000 per order target
   - Transit time variance: <2 days target
   - Resilience score: >80/100 target

5. **Build Measurement System**
   - Data collection: automated tracking
   - Calculation: real-time metric computation
   - Reporting: dashboards and alerts
   - Review: weekly performance reviews

6. **Test Metric Alignment**
   - Scenario: optimize for each metric
   - Compare outcomes: do metrics drive right decisions?
   - Identify conflicts: when metrics conflict
   - Refine metrics: adjust based on outcomes

**Deliverables:**
- KPI framework with primary metrics
- Leading indicator dashboard
- Metric target definitions
- Measurement system design
- Metric alignment test results

