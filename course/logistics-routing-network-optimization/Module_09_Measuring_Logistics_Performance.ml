# Module 9: Measuring Logistics Performance

**Problem:** Wrong metrics lead to wrong decisions  
**Capability:** Performance Measurement and KPI Design  
**Inspiration:** Operations metrics and outcome measurement

---

## Mindset Shift

> "Measure what matters. Faster is sometimes worse."

---

## Learning Objectives

### On-Time-In-Full (OTIF)

- On-time: delivery within promised time window
- In-full: complete order quantity delivered
- Why OTIF matters: customer satisfaction, trust
- OTIF calculation: percentage of perfect deliveries
- The difference between on-time and in-full
- Why both dimensions matter

### Cost-to-Serve

- Route cost: direct transportation costs
- Delay cost: penalties, expedited shipping
- Stockout cost: lost sales, customer impact
- Total cost-to-serve: all costs to deliver order
- Why cost-to-serve matters more than route cost
- The difference between cost and value

### Variance Reduction

- Transit time variance: variability in delivery times
- Why variance matters: predictability enables planning
- Variance reduction: making deliveries more consistent
- The trade-off between speed and consistency
- When consistency matters more than speed

### Resilience Metrics

- Recovery time: how quickly system recovers from disruption
- Disruption frequency: how often disruptions occur
- Impact severity: magnitude of disruption effects
- Resilience score: ability to maintain performance under stress
- Why resilience matters: long-term reliability

