## Practical Exercise

### Map a Real Logistics Network

**Objective:** Build network awareness of a real logistics system

**Steps:**

1. **Choose a Logistics Network**
   - Select a real network you know (company, region, mode)
   - Examples: e-commerce fulfillment, regional distribution, global shipping

2. **Identify Network Components**
   - Map all nodes (origins, hubs, destinations)
   - Document all lanes (routes, modes, carriers)
   - Identify capacity constraints at each node
   - Mark known chokepoints

3. **Analyze Network Stress**
   - When does the network experience peak demand?
   - Which nodes become bottlenecks?
   - Which lanes experience congestion?
   - What causes cascading failures?

4. **Document Physical vs Contractual Reality**
   - What routes are contracted?
   - What routes actually happen?
   - Where do delays occur?
   - What's the gap between plan and reality?

5. **Calculate Transit Time Variability**
   - Collect historical transit time data
   - Calculate mean, median, and percentiles
   - Identify distribution shape
   - Document when averages are misleading

**Deliverables:**
- Network diagram showing nodes, lanes, and constraints
- Bottleneck analysis identifying critical stress points
- Transit time distribution analysis
- Gap analysis: contractual vs. physical reality
- Network stress scenario documentation

