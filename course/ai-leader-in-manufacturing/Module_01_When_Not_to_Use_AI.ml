## Practical Exercise

### Identify When Not to Use AI

**Objective:** Develop the ability to recognize when AI is the wrong solution

**Steps:**

1. **Problem Analysis**
   - Select a business problem from your organization
   - Document the problem statement
   - Identify stakeholders and their needs

2. **AI Suitability Assessment**
   - Does this problem require AI?
   - What data is available and reliable?
   - How stable is the problem domain?
   - What are the risks of automation?
   - What alternatives exist?

3. **Decision Framework**
   - Create a decision matrix for AI vs alternatives
   - Assess data availability vs decision urgency
   - Evaluate stability vs change requirements
   - Identify automation risks
   - Consider process redesign options

4. **Recommendation**
   - Make a recommendation: AI or not?
   - Justify your decision
   - Identify what would change your mind
   - Document the decision criteria

**Deliverables:**
- Problem analysis document
- AI suitability assessment
- Decision framework
- Recommendation with justification
- Alternative solutions considered

