### Success Indicators

- **Strategic restraint**
  - Questions about whether AI is needed come before questions about how to build it
  - Recognition that not every problem needs AI
  - Ability to say "no" to AI projects

- **Problem-first thinking**
  - Understanding the problem before proposing solutions
  - Recognition that AI is a tool, not a goal
  - Focus on outcomes, not technology

- **Risk awareness**
  - Understanding when automation increases risk
  - Recognition of data limitations
  - Awareness of stability requirements

