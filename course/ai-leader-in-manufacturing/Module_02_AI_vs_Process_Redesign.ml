## Workshop

### Identify Where Process Change Beats AI Investment

**Objective:** Develop the ability to distinguish between process problems and AI opportunities

**Activity Structure:**

1. **Process Mapping**
   - Map a current process in detail
   - Identify bottlenecks and inefficiencies
   - Document pain points and waste
   - Understand current performance

2. **Root Cause Analysis**
   - Why does this process exist?
   - What problems does it solve?
   - What problems does it create?
   - What would an ideal process look like?

3. **Process Redesign Options**
   - How could this process be simplified?
   - What waste could be eliminated?
   - How could standardization help?
   - What would Lean principles suggest?

4. **AI Opportunity Assessment**
   - Where would AI add value?
   - What data would be needed?
   - How would AI improve outcomes?
   - What are the risks and costs?

5. **Decision Framework**
   - Should we redesign the process first?
   - Should we use AI on the current process?
   - Should we redesign and then add AI?
   - Should we skip AI entirely?

**Deliverables:**
- Process map with pain points
- Root cause analysis
- Process redesign recommendations
- AI opportunity assessment
- Decision: process first, AI first, or both
- Implementation roadmap

