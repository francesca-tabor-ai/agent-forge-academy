## Exercise

### Build vs Buy Analysis for a Planning System

**Objective:** Develop the ability to make sound build vs buy decisions

**Scenario:** Your organization needs a production planning system with AI capabilities.

**Analysis Framework:**

1. **Strategic Assessment**
   - Is this a differentiating capability?
   - Does it provide competitive advantage?
   - How does it align with strategy?
   - What is the strategic value?

2. **Market Assessment**
   - What vendors offer this capability?
   - How mature is the vendor market?
   - What is the quality of vendor solutions?
   - How do vendor solutions compare?

3. **Build Assessment**
   - What would it take to build this?
   - What talent is required?
   - What is the development timeline?
   - What are the ongoing costs?
   - What are the risks?

4. **Buy Assessment**
   - What vendors are available?
   - What are the licensing costs?
   - What is the integration complexity?
   - What is the lock-in risk?
   - What is the vendor support quality?

5. **Total Cost Analysis**
   - Build: development + maintenance + talent
   - Buy: licensing + integration + support
   - Risk-adjusted costs
   - Strategic value consideration
   - Long-term cost comparison

6. **Decision and Rationale**
   - Build or buy recommendation
   - Justification for the decision
   - Risk mitigation strategies
   - Implementation approach
   - Success criteria

**Deliverables:**
- Strategic assessment
- Market analysis
- Build vs buy cost comparison
- Risk assessment
- Decision recommendation
- Implementation plan

