## Case Review

### AI Failure That Triggered Operational or Legal Fallout

**Case Study Framework:**

1. **The System**
   - What the AI was designed to do
   - How it was deployed
   - Who was responsible
   - What governance existed

2. **The Failure**
   - What went wrong
   - When it was discovered
   - Who was affected
   - What the impact was

3. **The Fallout**
   - Operational consequences
   - Legal consequences
   - Reputational damage
   - Financial impact
   - Regulatory response

4. **Root Causes**
   - Why did it fail?
   - What accountability was missing?
   - What bias existed?
   - What explainability was lacking?
   - What risk management failed?

5. **Lessons Learned**
   - What should have been done differently?
   - How could accountability have been better?
   - How could bias have been prevented?
   - How could risk have been managed?
   - What governance was needed?

**Discussion Points:**
- Who was accountable for this failure?
- How could accountability have been better?
- What bias existed in the system?
- How could explainability have helped?
- What regulatory risks were present?
- How could this have been prevented?
- What would you do differently?

