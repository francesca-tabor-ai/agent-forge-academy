## Exercise

### Pre-Mortem a Large AI Rollout

**Objective:** Anticipate failure modes before they happen

**Scenario:** Your organization is planning a large-scale AI rollout across multiple manufacturing sites.

**Pre-Mortem Framework:**

1. **Assume Failure**
   - Imagine the rollout has failed
   - What went wrong?
   - When did it fail?
   - What was the impact?

2. **Identify Failure Modes**
   - Model drift and degradation
   - Over-automation issues
   - Incentive misalignment
   - Crisis amplification
   - Integration failures
   - Data quality issues
   - Organizational resistance
   - Technical failures

3. **Root Cause Analysis**
   - Why did each failure mode occur?
   - What could have prevented it?
   - What signals were missed?
   - What assumptions were wrong?

4. **Prevention Strategies**
   - How to prevent each failure mode
   - What monitoring is needed
   - What safeguards to put in place
   - How to detect early warning signals
   - What contingency plans are needed

5. **Risk Prioritization**
   - Which failure modes are most likely?
   - Which have the highest impact?
   - Which are hardest to detect?
   - Which are hardest to fix?
   - How to prioritize prevention efforts

6. **Action Plan**
   - What to do before rollout
   - What monitoring to implement
   - What safeguards to put in place
   - How to detect problems early
   - What contingency plans to prepare

**Deliverables:**
- Failure mode catalog
- Root cause analysis
- Prevention strategies
- Risk prioritization
- Monitoring plan
- Contingency plans
- Action plan

