## Evaluation Criteria

### Strategic Coherence
- Does the roadmap align with business strategy?
- Are priorities clearly justified?
- Is there a clear strategic vision?
- Do decisions support the vision?

### Restraint and Prioritization
- Are use cases appropriately prioritized?
- Is there strategic restraint (saying no)?
- Are resources allocated wisely?
- Is the scope realistic?

### Risk Awareness
- Are risks identified and assessed?
- Is there a risk management approach?
- Are ethics and accountability addressed?
- Are failure modes considered?

### Alignment with Business Reality
- Is the roadmap executable?
- Are assumptions realistic?
- Is the timeline achievable?
- Are resources available?
- Does it address real business needs?

