# Capstone: 2-Year Global AI Roadmap

**Problem:** Translating AI strategy into executable roadmap  
**Capability:** Strategic AI Roadmap Development  
**Inspiration:** Strategic planning, roadmap development, program management

---

## Capstone Objective

Design a 2-year AI roadmap for a global manufacturing or supply-chain organization that demonstrates strategic coherence, restraint, risk awareness, and alignment with business reality.

---

## Capstone Task

### Design a 2-Year Global AI Roadmap

Create a comprehensive AI roadmap that includes:

1. **Priority Use Cases**
   - Which use cases to pursue (and why)
   - Which use cases to avoid (and why)
   - Prioritization rationale
   - Strategic alignment
   - Expected value and impact

2. **Build vs Buy Rationale**
   - For each use case: build or buy?
   - Strategic differentiation assessment
   - Total cost of ownership analysis
   - Vendor evaluation (if buying)
   - Internal capability assessment (if building)

3. **Governance Model**
   - Organizational structure for AI
   - Governance framework
   - Decision-making authority
   - Accountability structures
   - Cross-functional alignment approach

4. **Risk and Ethics Framework**
   - Risk assessment for each use case
   - Ethics and bias considerations
   - Accountability structures
   - Regulatory compliance approach
   - Crisis management plans

5. **Talent and Operating Model**
   - Talent requirements
   - Hiring vs development strategy
   - Operating model design
   - Team structure
   - Capability building plan

6. **Financial Impact Expectations**
   - Portfolio-level ROI expectations
   - Risk reduction value
   - Organizational learning value
   - Capability building investment
   - Long-term value creation

