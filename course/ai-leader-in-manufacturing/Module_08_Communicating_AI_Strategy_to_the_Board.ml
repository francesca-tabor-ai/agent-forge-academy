## Role Play

### Present an AI Roadmap to a Skeptical Board

**Objective:** Practice communicating AI strategy to skeptical executives

**Scenario:** Present a 2-year AI roadmap to a board that is skeptical about AI investments.

**Role Play Structure:**

1. **Preparation**
   - Understand the board's concerns
   - Prepare your roadmap
   - Anticipate questions
   - Prepare responses to skepticism

2. **Presentation**
   - Frame AI as risk-managed investment
   - Avoid hype and be realistic
   - Set appropriate expectations
   - Address concerns directly

3. **Q&A Handling**
   - Respond to skeptical questions
   - Address concerns honestly
   - Provide evidence and examples
   - Maintain credibility

4. **Failure Scenarios**
   - How to handle questions about failures
   - How to address "what if it doesn't work"
   - How to communicate risks
   - How to maintain confidence

5. **Feedback and Reflection**
   - What worked well?
   - What could be improved?
   - How did you handle skepticism?
   - What would you do differently?

**Key Elements:**
- Clear value proposition
- Risk-managed approach
- Realistic expectations
- Honest communication
- Evidence and examples
- Responsive to concerns

