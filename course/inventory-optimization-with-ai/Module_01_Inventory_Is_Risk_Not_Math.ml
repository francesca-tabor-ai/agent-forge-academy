## Discussion

### When "Optimal" Inventory Causes Business Failure

**Scenario Analysis:**

1. **The Perfect Formula Disaster**
   - Case: Company uses EOQ formula with perfect assumptions
   - Reality: Demand volatility, supplier delays, quality issues
   - Outcome: Stockouts during peak demand, excess during slow periods
   - Lesson: Formulas optimize for the wrong problem

2. **The Cost Minimization Trap**
   - Case: Focus on minimizing holding costs
   - Reality: Stockout costs are 10x holding costs
   - Outcome: Frequent stockouts, customer churn
   - Lesson: Wrong cost function leads to wrong decisions

3. **The Single-Item Optimization**
   - Case: Optimize each SKU independently
   - Reality: Shared warehouse space, budget constraints
   - Outcome: System-level failures despite item-level optimization
   - Lesson: Local optimization ≠ global optimization

**Discussion Questions:**
- When have you seen "optimal" inventory fail?
- What assumptions did the model make that reality violated?
- What was the actual cost of the failure?
- How could risk awareness have prevented it?

