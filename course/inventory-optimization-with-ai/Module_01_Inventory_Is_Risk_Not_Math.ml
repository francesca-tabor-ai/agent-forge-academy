## Practical Exercise

### Identify Real-World Inventory Failures

**Objective:** Map textbook assumptions to real-world failures

**Steps:**

1. **Choose a Real Inventory Problem**
   - Select a product or SKU you know well
   - Document current inventory policy (if any)

2. **Apply Textbook Formula**
   - Calculate EOQ or similar "optimal" level
   - Document all assumptions made

3. **Compare to Reality**
   - What assumptions break in practice?
   - What uncertainty sources exist?
   - What constraints are ignored?

4. **Calculate Real Costs**
   - Stockout cost (lost sales, production impact, customer trust)
   - Excess cost (holding, obsolescence, opportunity cost)
   - Which is higher? Why?

5. **Design Risk-Based Policy**
   - What uncertainty are you hedging against?
   - What service level do you actually need?
   - What constraints must you respect?

**Deliverables:**
- Comparison: textbook formula vs. reality
- Risk assessment: uncertainty sources and their impact
- Cost analysis: stockout vs. excess costs
- Risk-based inventory policy framework

