# Module 2: Onboarding Is a Performance Problem

**Duration:** 90 minutes  
**Problem:** Slow onboarding  
**Capability:** Role-Based Onboarding Guides  
**Inspiration:** SaaS onboarding flows

---

## Mindset Shift

> "Onboarding is how quickly someone becomes valuable — not how much they're told."

---

## Learning Objectives

### How SaaS Products Ramp Users Fast

- Progressive disclosure: show what's needed, when it's needed
- Contextual help: guidance at the moment of action
- Success metrics: completion rates, time-to-first-value
- Personalization: different paths for different roles

### How AI Tailors Onboarding by Role, Seniority, and Project Type

- Role-based content filtering
- Seniority-appropriate depth
- Project-specific guidance
- Adaptive learning paths

### What New Joiners Actually Need in Their First 30 Days

- Week 1: Access, setup, first tasks
- Week 2: Core workflows, key relationships
- Week 3: Project ownership, decision-making
- Week 4: Independence and contribution

---

## Practical Exercise

### Build a Role-Based Onboarding Flow

**Step 1: Map Roles to Needs**

Create a matrix:
- **Role:** [e.g., Designer, Engineer, PM, Sales]
- **Day 1 needs:** [Access, tools, introductions]
- **Week 1 needs:** [Core workflows, key systems]
- **Month 1 needs:** [Project ownership, decision-making]

**Step 2: Design the Flow**

- Entry point: How do they start?
- Checkpoints: What must they complete?
- Resources: What's available when?
- Escalation: When do they need human help?

**Step 3: Pressure-Test It with a Recent Joiner**

- Ask someone who joined in the last 3 months:
  - What did you need that wasn't there?
  - What did you get that you didn't need?
  - What would have made you productive faster?

**Step 4: Remove Anything That Doesn't Accelerate Confidence**

- Delete: "Nice to know" information
- Defer: Advanced topics until needed
- Focus: Only what enables immediate contribution

---

## Behaviour Installed

### Success Indicators

- **Faster ramp-up**
  - Measurable reduction in time-to-first-contribution
  - Earlier project ownership
  - Reduced "I don't know how to..." moments

- **Fewer "Can You Show Me How..." Moments**
  - Self-service guidance available
  - Contextual help when needed
  - Reduced burden on managers and peers

---

## Key Takeaways

1. **Onboarding is a performance problem, not an information problem**
2. **SaaS onboarding patterns apply to human onboarding**
3. **Role-based personalization accelerates relevance**
4. **Less is more: remove everything that doesn't enable immediate contribution**

