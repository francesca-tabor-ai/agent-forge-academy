## Practical Exercise

### Ask Real "How Do We..." Questions

**Setup:**
- Identify 3-5 real questions your team asks regularly
- Examples:
  - "How do we onboard a new client in [system]?"
  - "What's our process for handling [specific scenario]?"
  - "Who owns [process] and what are the key steps?"

**Compare Time-to-Answer:**

1. **Manual Search Method:**
   - Time yourself searching through:
     - Slack history
     - Documentation sites
     - Email threads
     - Shared drives
   - Record: time taken, confidence level, completeness

2. **AI Knowledge Assistant Method:**
   - Ask the same questions to your AI assistant
   - Record: time taken, confidence level, completeness
   - Note: Did it surface things you forgot existed?

**Improve Prompts Until Answers Are Genuinely Useful:**

- Start with basic question
- Refine based on initial answer
- Add context: role, urgency, specific constraints
- Test edge cases: "What if...", "When should we..."
- Document the prompt patterns that work best

