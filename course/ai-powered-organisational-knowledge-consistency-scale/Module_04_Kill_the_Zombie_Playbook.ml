# Module 4: Kill the Zombie Playbook

**Duration:** 90 minutes  
**Problem:** Outdated playbooks  
**Capability:** Auto-Refresh Knowledge Links  
**Inspiration:** Wiki automation

---

## Mindset Shift

> "Static knowledge decays faster than no knowledge."

---

## Learning Objectives

### Why Playbooks Rot

- The maintenance burden: who owns what?
- The update problem: when does it get refreshed?
- The trust problem: outdated info destroys credibility
- The discovery problem: people stop looking if it's wrong

### How AI Links Guidance to Live, Relevant Examples

- Dynamic linking: connect playbooks to real work
- Example surfacing: show current, relevant instances
- Version awareness: what's current vs what's historical
- Contextual freshness: when was this last validated?

### How to Maintain a Single Source of Truth Without Admin Overhead

- Auto-linking to source material
- Example-based documentation
- Community validation (who used this recently?)
- Decay detection (when was this last referenced?)

---

## Practical Exercise

### Identify a Dead Playbook

**Step 1: Find a Zombie**

Look for playbooks that:
- Haven't been updated in 6+ months
- Reference tools/processes that no longer exist
- People avoid because "it's probably outdated"
- Have conflicting information with current practice

**Step 2: Replace It with Dynamic Links to Real Work**

Instead of static steps, create:
- **Links to recent examples:** "See how we did this in [Project X]"
- **Current tool references:** Link to actual tools, not descriptions
- **Live process maps:** Connect to current workflows
- **Recent validations:** "Last verified: [date] by [person]"

**Step 3: Decide Who Owns What — and What No Longer Needs Owning**

Create ownership model:
- **Core processes:** Who owns the standard?
- **Examples:** Who maintains the example library?
- **Validation:** Who confirms it's still current?
- **Retirement:** When does a playbook get archived?

Design for:
- Low maintenance: auto-linking reduces manual updates
- Community ownership: many can contribute examples
- Clear accountability: someone owns the core
- Graceful decay: outdated content is marked, not deleted

---

## Behaviour Installed

### Success Indicators

- **Fewer Outdated References**
  - Playbooks link to current examples
  - Outdated content is clearly marked
  - People trust the guidance again

- **Trust Restored in Shared Guidance**
  - People actually use playbooks
  - Confidence that information is current
  - Reduced "is this still accurate?" questions

---

## Key Takeaways

1. **Static knowledge decays — make it dynamic**
2. **Link to real work, not descriptions of work**
3. **Auto-linking reduces maintenance burden**
4. **Clear ownership + community contribution = sustainable knowledge**

