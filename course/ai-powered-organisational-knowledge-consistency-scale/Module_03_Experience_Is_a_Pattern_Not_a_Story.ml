## Behaviour Installed

### Success Indicators

- **Faster Planning**
  - Reduced "starting from scratch" time
  - Earlier identification of risks and opportunities
  - More confident project scoping

- **Fewer Repeated Mistakes**
  - Known failure modes avoided
  - Proven solutions reused
  - Lessons learned actually applied

- **Less Dependence on Memory or Senior Availability**
  - Organizational memory accessible to all
  - Experience scales beyond individual recall
  - Juniors can access senior-level context

