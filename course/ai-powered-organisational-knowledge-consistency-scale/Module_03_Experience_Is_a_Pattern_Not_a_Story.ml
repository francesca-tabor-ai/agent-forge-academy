# Module 3: Experience Is a Pattern, Not a Story

**Duration:** 90 minutes  
**Problem:** Reinventing solutions  
**Capability:** "What Worked Before" Prompts  
**Inspiration:** Case-based reasoning systems

---

## Mindset Shift

> "We don't need answers — we need precedent."

---

## Learning Objectives

### How Case-Based Systems Reuse Judgement, Not Templates

- Case-based reasoning: similar problems, similar solutions
- Why templates fail: context matters
- How to extract reusable patterns from past work
- The difference between copying and adapting

### How AI Surfaces Similar Past Work + Lessons

- Semantic similarity: finding related projects
- Pattern recognition: what worked, what didn't
- Context extraction: key decisions and rationale
- Lesson synthesis: turning stories into reusable insights

### How to Adapt Precedent Without Copy-Paste Thinking

- When to follow precedent exactly
- When to adapt for new context
- How to identify what's essential vs what's circumstantial
- Avoiding cargo-cult solutions

---

## Practical Exercise

### Start a New Project

**Step 1: Identify Your New Project**

Choose a real project you're about to start:
- New client engagement
- New product feature
- New process implementation
- New team initiative

**Step 2: Pull Insights from 2–3 Similar Past Projects**

Using your AI assistant, ask:
- "What projects have we done that are similar to [your project]?"
- "What worked well in those projects?"
- "What challenges did we face and how did we solve them?"
- "What would we do differently?"

**Step 3: Apply Only What Materially Improves Outcomes**

Review the insights and decide:
- **Adopt:** This directly applies and will help
- **Adapt:** This is relevant but needs modification
- **Avoid:** This didn't work or isn't relevant
- **New:** This is genuinely new territory

Create a plan that:
- Leverages proven patterns
- Avoids known pitfalls
- Adapts for current context
- Documents new learnings for future use

