# Module 5: Nudge, Don't Nag

**Duration:** 90 minutes  
**Problem:** Low engagement with knowledge  
**Capability:** Contextual Workflow Nudges  
**Inspiration:** Consumer app nudging

---

## Mindset Shift

> "People don't ignore knowledge — they ignore interruptions."

---

## Learning Objectives

### How Consumer Apps Change Behaviour Without Friction

- Timing: show help when it's needed, not when it's convenient for you
- Context: relevant to what they're doing right now
- Value: clearly helpful, not just informational
- Dismissibility: easy to ignore if not relevant

### How AI Nudges Appear in the Moment of Need

- Workflow detection: "I see you're starting [task]"
- Contextual relevance: "Here's what helped others with this"
- Proactive assistance: before they ask, not after they're stuck
- Non-intrusive: helpful, not demanding

### Where Nudges Help — and Where They Must Stay Silent

- **Help:** Starting new tasks, encountering errors, exploring new areas
- **Silent:** In flow, during focused work, when they're already expert
- **Escalate:** When nudges aren't enough, connect to human help

---

## Practical Exercise

### Design Three Contextual Nudges for Real Workflows

**Step 1: Identify High-Value Nudge Moments**

Choose three workflows where knowledge would help:
- Example 1: Starting a new client project
- Example 2: Encountering an error in a system
- Example 3: Beginning a process you haven't done in a while

**Step 2: Design the Nudge**

For each moment, design:
- **Trigger:** When does it appear?
- **Content:** What does it say/show?
- **Action:** What can they do with it?
- **Dismissal:** How do they close it?

**Step 3: Test Whether They Help or Annoy**

Test with real users:
- Does it appear at the right time?
- Is the content actually useful?
- Does it feel helpful or intrusive?
- Would they want to see it again?

**Step 4: Remove Anything That Breaks Flow**

Eliminate:
- Nudges that interrupt focused work
- Information that's not immediately actionable
- Prompts that feel like nagging
- Anything that adds friction

---

## Behaviour Installed

### Success Indicators

- **Higher Adoption**
  - People actually click on nudges
  - Knowledge is accessed when relevant
  - Reduced "I didn't know that existed" moments

- **Knowledge Feels Helpful, Not Imposed**
  - Nudges are welcomed, not dismissed
  - People appreciate the timing
  - Knowledge feels like support, not surveillance

---

## Key Takeaways

1. **Timing and context matter more than content**
2. **Nudges should feel helpful, not mandatory**
3. **Know when to stay silent**
4. **Test with real users: help or annoy?**

---

## Next Steps

- Identify your top 3 nudge-worthy moments
- Design and test contextual nudges
- Measure: engagement rates and user feedback
- Iterate: remove what breaks flow, amplify what helps

