# Apprenticeship Lab: The AI Mentor

**Duration:** 90 minutes  
**Wild Capability:** AI Mentor for Junior Staff  
**Inspiration:** Coaching platforms

---

## Mindset Shift

> "Good mentoring scales judgement, not answers."

---

## What You'll Explore

### What an AI Mentor Should and Should Not Do

**Should Do:**
- Provide context and frameworks
- Suggest approaches based on precedent
- Help structure thinking
- Surface relevant examples and patterns
- Escalate when human judgment is needed

**Should Not Do:**
- Make decisions that require human judgment
- Replace human relationships and coaching
- Provide answers without context
- Operate without guardrails
- Bypass proper escalation paths

### How AI Supports Juniors Without Replacing Seniors

- **AI handles:** Information retrieval, pattern matching, basic guidance
- **Humans handle:** Complex judgment, relationship building, career development
- **Together:** AI provides context, humans provide wisdom
- **Escalation:** Clear rules for when to involve humans

### How to Escalate to Humans at the Right Moment

- **Auto-escalate:** High-risk decisions, sensitive topics, ambiguous situations
- **Suggest escalation:** When AI confidence is low, when precedent is unclear
- **Never escalate:** Routine questions, information lookups, pattern matching
- **Escalation paths:** Who to contact, when, and how

