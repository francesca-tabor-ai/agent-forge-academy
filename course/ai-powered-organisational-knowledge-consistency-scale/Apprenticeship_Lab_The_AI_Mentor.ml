## Practical Exercise

### Simulate a Junior Asking for Guidance

**Scenario Setup:**

Choose a realistic scenario:
- "I need to design a new feature for [product]"
- "A client is asking for [complex request] — how should I respond?"
- "I'm stuck on [technical problem] — where do I start?"
- "I need to present [topic] to [audience] — what should I cover?"

**Step 1: Evaluate AI Advice**

Have the AI mentor respond to the scenario:
- What guidance does it provide?
- What context does it surface?
- What examples does it reference?
- What questions does it ask?

**Step 2: Compare AI Advice vs Human Coaching**

Compare:
- **Breadth:** Does AI cover what a human would?
- **Depth:** Does AI go deep enough?
- **Judgment:** Where does human judgment add value?
- **Relationship:** What does human interaction provide that AI can't?

**Step 3: Define Guardrails and Escalation Rules**

Create rules for:
- **When AI can fully handle:** Clear, low-risk, precedent-based questions
- **When AI should suggest human help:** Ambiguous, medium-risk, precedent-unclear
- **When AI must escalate immediately:** High-risk, sensitive, no-clear-precedent
- **Escalation paths:** Who, when, how

