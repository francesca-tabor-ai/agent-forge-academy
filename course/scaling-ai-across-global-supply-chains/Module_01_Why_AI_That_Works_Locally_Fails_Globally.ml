## Case Study

### Successful Pilot That Collapsed at Rollout

**Scenario:** An AI system that achieved 95% accuracy in a single region pilot, but failed catastrophically when rolled out to 15 regions simultaneously.

**Case Study Framework:**

1. **The Pilot Success**
   - Initial region performance metrics
   - What made it work locally
   - Key success factors identified
   - Stakeholder confidence and expectations

2. **The Rollout Plan**
   - Scaling strategy (copy vs adapt)
   - Assumptions about transferability
   - Resource allocation and timeline
   - Risk assessment and mitigation

3. **The Collapse**
   - Where and why it failed
   - Regional differences that broke the system
   - Coordination failures
   - Data and infrastructure gaps
   - Performance degradation patterns

4. **The Root Causes**
   - What was missed in planning
   - Assumptions that proved false
   - Coordination breakdowns
   - Technical vs organizational failures
   - Early warning signals that were ignored

**Discussion Questions:**
- What made the pilot succeed but rollout fail?
- Which failures were technical vs coordination?
- What regional differences were underestimated?
- How could the rollout have been designed differently?
- What early signals indicated problems?

