- The cost of forcing uniformity
- When centralization creates bottlenecks
- The risk of regional fragmentation
- Finding the right balance point
- Governance without paralysis

### The Cost of "Just Copying the Model"

- Why model replication fails
- Context that doesn't transfer
- Data distribution differences
- Infrastructure assumptions that break
- The hidden costs of naive scaling

