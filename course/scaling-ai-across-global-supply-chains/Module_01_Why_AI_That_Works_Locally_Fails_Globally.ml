## Practical Exercise

### Analyze a Scale Failure in Your Context

**Objective:** Identify why a system that worked locally failed at scale

**Steps:**

1. **Select a System**
   - Choose an AI system that worked in one context but failed at scale
   - Document local success metrics
   - Identify scaling assumptions

2. **Map Regional Differences**
   - Demand patterns and variability
   - Data quality and availability
   - Process and workflow differences
   - Infrastructure and technical constraints
   - Regulatory and compliance requirements
   - Cultural and behavioral factors

3. **Identify Failure Modes**
   - Technical failures (model performance, infrastructure)
   - Coordination failures (communication, alignment)
   - Data failures (quality, availability, distribution)
   - Organizational failures (governance, ownership)
   - Process failures (workflow, adoption)

4. **Design Prevention Strategies**
   - What would have prevented each failure?
   - Early warning signals to monitor
   - Risk mitigation approaches
   - Alternative scaling strategies

**Deliverables:**
- Scale failure analysis document
- Regional difference mapping
- Failure mode categorization
- Prevention strategy framework
- Early warning signal checklist

