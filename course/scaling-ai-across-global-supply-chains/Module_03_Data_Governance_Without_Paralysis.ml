## Case Study

### Governance That Blocked vs Governance That Enabled

**Scenario:** Compare two approaches to data governance — one that created bottlenecks and slowed development, and one that enabled rapid scaling while maintaining quality.

**Analysis:**

1. **The Blocking Approach**
   - Over-standardization
   - Approval bottlenecks
   - Lack of self-service
   - Slow decision processes
   - Impact on development velocity

2. **The Enabling Approach**
   - Pragmatic standards
   - Self-service with guardrails
   - Clear ownership
   - Fast decision processes
   - Impact on scale and quality

3. **Key Differences**
   - Philosophy: control vs enablement
   - Processes: approval vs self-service
   - Standards: perfection vs pragmatism
   - Ownership: centralized vs distributed
   - Tools: manual vs automated

**Discussion Points:**
- What made one approach block and the other enable?
- How did governance philosophy affect outcomes?
- What processes created bottlenecks?
- How did tools and automation help?
- What balance worked best?

