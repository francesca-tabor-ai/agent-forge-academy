## Key Concepts

### Operating Model Options

- **Centralized model**
  - Single AI team serving all regions
  - Strong global standards
  - Risk of bottlenecks and local disconnect

- **Federated model**
  - Regional AI teams with autonomy
  - Strong local fit
  - Risk of fragmentation and duplication

- **Hybrid model**
  - Central platform team + regional product teams
  - Balance of standards and flexibility
  - Requires clear interfaces

### Team Structures

- **Platform teams**
  - Build shared AI capabilities
  - Enable product teams
  - Focus on infrastructure and tools
  - Avoid becoming bottlenecks

- **Product teams**
  - Build business solutions
  - Use platform capabilities
  - Focus on business value
  - Balance speed and standards

- **Regional champions**
  - Bridge global and local
  - Represent regional needs
  - Enable local adoption
  - Coordinate with global teams

### Decision Rights Framework

- **Global decisions**
  - Standards and architecture
  - Strategic direction
  - Major investments
  - Governance and compliance

- **Regional decisions**
  - Local customization
  - Regional priorities
  - Tactical adaptations
  - Local resource allocation

- **Shared decisions**
  - Platform roadmap
  - Cross-region initiatives
  - Resource conflicts
  - Escalation processes

