## Practical Exercise

### Run Three Scenarios on a Live Project

**Base Case Scenario:**
- Current scope, timeline, and resources
- Baseline financial forecast
- Assumptions documented

**Scenario A: Scope Expansion**
- Additional deliverables requested
- Impact on timeline and resources
- Financial implications
- Margin effects

**Scenario B: Timeline Compression**
- Accelerated delivery requirement
- Resource implications
- Cost impacts
- Quality and margin trade-offs

**Scenario C: Resource Constraint**
- Key resource unavailability
- Alternative resourcing options
- Cost and timeline impacts
- Margin implications

### Compare Financial Outcomes and Trade-Offs

**Analysis Framework:**
- Financial impact comparison
- Margin effects across scenarios
- Risk assessment for each scenario
- Trade-off identification

**Deliverables:**
- Scenario comparison matrix
- Financial impact summary
- Risk assessment by scenario
- Trade-off analysis

### Decide Which Levers Leadership Actually Controls

**Control Analysis:**
- Which factors are controllable?
- Which factors are external?
- What actions can leadership take?
- What must be accepted or mitigated?

**Decision Framework:**
- Scenario selection criteria
- Action prioritization
- Resource allocation decisions
- Risk acceptance thresholds

