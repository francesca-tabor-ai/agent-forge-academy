## Practical Exercise

### Review a Historical Project Where Margin Was Lost

**Scenario:** Analyze a completed project with margin erosion

**Steps:**
1. Review project timeline and margin progression
2. Identify key decision points
3. Map margin drift to specific events
4. Document when problems became visible

### Replay It with Continuous Margin Signals

**Activity:** Reconstruct the project with continuous monitoring

**Deliverables:**
- Continuous margin signal timeline
- Early warning indicators that would have triggered
- Signal-to-action mapping
- Intervention point identification

### Identify the Moment Intervention Would Have Changed the Outcome

**Analysis:**
- Cost of early intervention vs. late intervention
- Decision points where action would have mattered
- Leadership actions that would have preserved margin
- Lessons for future projects

