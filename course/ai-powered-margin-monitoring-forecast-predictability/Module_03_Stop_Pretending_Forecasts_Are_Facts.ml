## Practical Exercise

### Compare Two Forecasts with Different Confidence Scores

**Scenario:** Two projects with similar margin forecasts but different confidence levels

**Project A:**
- Forecast: 15% margin
- Confidence: 85% (high)
- Data quality: Excellent
- Historical accuracy: Strong

**Project B:**
- Forecast: 15% margin
- Confidence: 45% (low)
- Data quality: Limited
- Historical accuracy: Variable

**Analysis:**
- What does each confidence level mean?
- How should leadership interpret the difference?
- What actions are appropriate for each?

### Decide How Leadership Action Changes Based on Confidence

**Decision Framework Exercise:**

**High Confidence (80%+):**
- Appropriate actions
- Resource allocation decisions
- Communication approach
- Risk management stance

**Medium Confidence (50-79%):**
- Appropriate actions
- Monitoring requirements
- Contingency planning
- Communication approach

**Low Confidence (<50%):**
- Appropriate actions
- Risk mitigation strategies
- Scenario planning needs
- Communication approach

### Define Thresholds for Escalation

**Escalation Framework:**
