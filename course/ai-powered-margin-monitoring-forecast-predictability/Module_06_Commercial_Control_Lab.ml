## Practical Exercise

### Simulate a Scope Change Mid-Delivery

**Scenario:** Active project with mid-delivery scope expansion request

**Initial Project:**
- Original scope defined
- Contract and pricing established
- Delivery in progress
- Margin tracking active

**Scope Change Request:**
- Additional deliverables requested
- Timeline implications
- Resource requirements
- Quality expectations

**Data Input:**
- Original project parameters
- Scope change details
- Current project status
- Commercial context

### Review AI-Suggested Commercial Responses

**AI Analysis Output:**

**Option 1: Scope Addition with Price Adjustment**
- Additional cost calculation
- Recommended price increase
- Timeline adjustment
- Resource requirements

**Option 2: Scope Substitution**
- Remove equivalent scope
- Maintain original pricing
- Timeline preservation
- Resource reallocation

**Option 3: Phased Approach**
- Defer new scope to next phase
- Maintain current phase integrity
- Future pricing discussion
- Timeline protection

**Option 4: Value-Based Renegotiation**
- Value assessment of new scope
- Strategic relationship consideration
- Long-term commercial impact
- Partnership approach

