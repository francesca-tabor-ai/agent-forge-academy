## Practical Exercise

### Review Margin-Risk Alerts for an Active Project

**Scenario:** Active project with margin-risk alerts triggered

**Alert Types:**
- Resource utilization anomalies
- Timeline deviation patterns
- Scope creep indicators
- Cost variance signals
- Quality risk indicators

**Analysis:**
- Alert severity assessment
- Root cause identification
- Pattern recognition
- Historical context

### Decide What Action Is Proportionate

**Action Framework:**

**Low-Risk Alerts:**
- Monitoring and observation
- Light-touch check-ins
- Documentation and tracking

**Medium-Risk Alerts:**
- Targeted intervention
- Team discussion and planning
- Resource adjustment
- Timeline review

**High-Risk Alerts:**
- Immediate intervention
- Leadership escalation
- Resource reallocation
- Scope or timeline adjustment

### Practice Non-Punitive Intervention Language

**Language Exercise:**

**Avoid:**
- Blame-focused language
- Accusatory tones
- Defensive positioning
- Punitive framing

**Use:**
- Problem-solving language
- Collaborative framing
- Supportive tone
- Solution-focused approach

**Examples:**
- "We've noticed a pattern that might impact margin. Let's explore solutions together."
- "The data suggests we might need to adjust our approach. What support do you need?"
- "I see an opportunity to protect margin here. How can we address this?"

