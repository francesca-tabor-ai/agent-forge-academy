## Hands-On

### Design a Planner-Facing Scheduling UI

**Objective:** Create a user interface that builds trust and enables adoption

**Requirements:**

1. **Explainability**
   - Show why decisions were made
   - Highlight constraints and trade-offs
   - Allow "what-if" exploration
   - Provide alternative views

2. **Visualization**
   - Clear, intuitive schedule display
   - Multiple views (Gantt, resource, timeline)
   - Interactive exploration
   - Mobile-friendly for floor access

3. **Override Support**
   - Easy override mechanism
   - Override tracking and explanation
   - Learning from overrides
   - Feedback loop to system

4. **Trust Building**
   - Show system confidence
   - Highlight uncertainties
   - Allow operator input
   - Demonstrate value

**Steps:**

1. **Define User Personas**
   - Production planner
   - Line supervisor
   - Operator
   - What does each need?

2. **Design Key Screens**
   - Schedule overview
   - Detailed schedule view
   - Override interface
   - Explanation/insights panel

3. **Prototype the UI**
   - Create wireframes or mockups
   - Show key interactions
   - Demonstrate explainability
   - Test with users

4. **Gather Feedback**
   - What works?
   - What's confusing?
   - What's missing?
   - How to improve?

**Deliverables:**
- User persona definitions
- UI wireframes/mockups
- Interaction flow diagrams
- Explanation mechanisms
- Override interface design
- Feedback and improvement plan

