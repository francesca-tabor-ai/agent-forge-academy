# Module 8: Trust, Transparency & Adoption

**Problem:** Schedules that aren't trusted or followed  
**Capability:** Trust-Building and Adoption  
**Inspiration:** Change management, user experience design, and organizational psychology

---

## Mindset Shift

> "A perfect schedule that isn't followed is worse than a good schedule that is. Build trust, not just algorithms."

---

## Learning Objectives

### Explainability for Planners

- **What planners need to understand:**
  - Why this sequence?
  - Why this timing?
  - Why not this alternative?
  - What assumptions were made?
  - What could go wrong?

- How to explain scheduling decisions
- The value of explainability
- When explainability matters most
- How to balance explainability with complexity

### Visual Schedules

- **Effective schedule visualization:**
  - Gantt charts
  - Resource timelines
  - Dependency graphs
  - Heat maps
  - Interactive dashboards

- What makes a good schedule visualization
- How to show constraints and trade-offs
- How to make schedules actionable
- How to support different user needs

### Override Tracking

- **Why track overrides:**
  - Learn from operator decisions
  - Identify system weaknesses
  - Build trust through transparency
  - Improve the system

- What to track (who, when, why, what changed, outcome)
- How to analyze override patterns
- How to use overrides to improve the system
- When overrides indicate trust issues

### Trust Decay and Recovery

- **How trust decays:**
  - Schedules that don't work
  - Ignoring operator feedback
  - Frequent rescheduling
  - Unexplained decisions
  - Over-automation

- **How to build trust:**
  - Start with simple, reliable schedules
  - Involve operators in design
  - Explain decisions
  - Learn from overrides
  - Allow local control

- How to recover from trust loss
- The cost of lost trust
- How to measure trust

