# Module 6: Human Behavior & Local Workarounds

**Problem:** Ignoring human behavior in scheduling systems  
**Capability:** Human-Centered Scheduling Design  
**Inspiration:** Human factors engineering, organizational behavior, and systems thinking

---

## Mindset Shift

> "Design for people, not robots. Operators will work around systems that don't respect their reality."

---

## Learning Objectives

### Operator Preferences

- **What operators care about:**
  - Predictable schedules
  - Reasonable workloads
  - Skill utilization
  - Autonomy and control
  - Recognition and fairness

- Why preferences matter
- How to incorporate preferences
- The cost of ignoring preferences
- When preferences conflict with optimization

### Informal Rules and Tribal Knowledge

- **What operators know that systems don't:**
  - Which machines are "fussy"
  - Which setups are tricky
  - Which operators work well together
  - Which times of day are problematic
  - Local shortcuts and workarounds

- How to capture tribal knowledge
- When to codify vs. when to allow flexibility
- The value of informal rules
- How to respect local knowledge

### Schedule Gaming

- **How operators game schedules:**
  - Padding estimates
  - Creating artificial constraints
  - Hiding capacity
  - Prioritizing preferred work
  - Building informal buffers

- Why gaming happens
- How to detect gaming
- When gaming is rational
- How to reduce gaming incentives

### Why Overrides Are Rational

- **When operators override schedules:**
  - Schedule doesn't account for reality
  - Urgent issues arise
  - Local knowledge suggests better approach
  - System is too rigid
  - Trust in system is low

- Why overrides are often correct
- How to learn from overrides
- When to allow vs. restrict overrides
- How to build trust to reduce overrides

