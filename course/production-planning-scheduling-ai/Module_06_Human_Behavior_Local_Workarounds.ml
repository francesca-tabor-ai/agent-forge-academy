## Role Play

### Present a Schedule to a Line Supervisor

**Objective:** Experience how schedules are received by operators

**Scenario:** You've built an "optimal" schedule. Now present it to a line supervisor who has been working in production for 20 years.

**Steps:**

1. **Prepare Your Presentation**
   - Explain the schedule logic
   - Highlight the benefits
   - Address potential concerns
   - Prepare for questions

2. **Present to the Supervisor**
   - Walk through the schedule
   - Explain the sequencing decisions
   - Show the optimization results
   - Ask for feedback

3. **Handle Objections**
   - "This won't work because..."
   - "We always do it this way..."
   - "This ignores..."
   - "What about..."

4. **Learn from Feedback**
   - What did the supervisor point out?
   - What constraints did you miss?
   - What preferences did you ignore?
   - What would make the schedule acceptable?

5. **Revise the Schedule**
   - Incorporate feedback
   - Address concerns
   - Find compromises
   - Re-present if needed

**Deliverables:**
- Initial schedule presentation
- List of supervisor objections
- Revised schedule incorporating feedback
- Reflection on what you learned
- Plan for building operator trust

