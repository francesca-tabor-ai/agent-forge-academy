# Module 2: Capacity Planning Under Real Constraints

**Problem:** Planning with theoretical capacity instead of effective capacity  
**Capability:** Reality-Based Capacity Planning  
**Inspiration:** Theory of Constraints, capacity management, and production planning

---

## Mindset Shift

> "Rated capacity is a lie. Effective capacity is the truth. Plan with the truth, not the lie."

---

## Learning Objectives

### Rated vs Effective Capacity

- **Rated capacity:** Theoretical maximum output under ideal conditions
- **Effective capacity:** Actual output considering all real-world factors
- The gap between rated and effective capacity
- Why rated capacity is misleading
- How to calculate effective capacity
- When effective capacity changes (shifts, seasons, experience)

### Labor Constraints

- Skill levels and experience impact on capacity
- Training time and learning curves
- Absenteeism and turnover rates
- Shift patterns and overtime limits
- Operator preferences and fatigue
- Cross-training and flexibility
- Why labor is often the real bottleneck

### Maintenance Windows

- Planned maintenance schedules
- Unplanned breakdowns and repairs
- Preventive vs. reactive maintenance
- Maintenance impact on capacity
- How to schedule around maintenance
- The cost of skipping maintenance

### Hidden Capacity Drains

- Setup and changeover time
- Quality issues and rework
- Material handling and movement
- Waiting for materials or tools
- Communication and coordination delays
- Administrative tasks and paperwork
- Meetings and training
- Why 100% utilization is impossible

