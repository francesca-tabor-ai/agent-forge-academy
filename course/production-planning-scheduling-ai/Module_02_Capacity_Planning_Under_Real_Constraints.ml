## Hands-On Exercise

### Estimate True Capacity from Historical Data

**Objective:** Calculate effective capacity from real production data

**Steps:**

1. **Gather Historical Data**
   - Production output by shift/day/week
   - Machine uptime and downtime
   - Labor hours worked vs. available
   - Quality metrics (scrap, rework)
   - Changeover frequencies and durations

2. **Calculate Rated Capacity**
   - Theoretical maximum output
   - Based on machine specifications
   - Based on standard labor hours
   - Based on ideal conditions

3. **Calculate Effective Capacity**
   - Actual output achieved
   - Account for downtime
   - Account for quality losses
   - Account for changeovers
   - Account for labor constraints

4. **Identify Capacity Drains**
   - Breakdowns and maintenance
   - Setup and changeover time
   - Quality issues
   - Material delays
   - Labor constraints
   - Administrative overhead

5. **Build Capacity Model**
   - Effective capacity by resource
   - Capacity by shift/day/week
   - Seasonal or temporal variations
   - Confidence intervals for capacity

**Deliverables:**
- Rated vs. effective capacity comparison
- Capacity drain analysis
- Effective capacity model
- Recommendations for capacity improvement
- Identification of the true bottleneck

