## Discussion

### When Better Schedules Increase Stress

**Scenario:** You've implemented a new scheduling system. The metrics show improvement:
- Higher throughput
- Better schedule adherence
- Lower WIP
- Fewer firefights

But operators report:
- Higher stress
- Less autonomy
- More pressure
- Lower job satisfaction

**Discussion Questions:**

1. **What's happening?**
   - Why are metrics improving but stress increasing?
   - What are we measuring vs. what matters?
   - Are we optimizing the wrong thing?

2. **The Metrics Problem**
   - Are throughput and adherence the right metrics?
   - What about operator well-being?
   - What about system resilience?
   - What about long-term sustainability?

3. **The Trade-offs**
   - Efficiency vs. flexibility
   - Control vs. autonomy
   - Optimization vs. robustness
   - Short-term vs. long-term

4. **Better Metrics**
   - What should we measure instead?
   - How to balance multiple objectives?
   - How to measure system health?
   - How to measure operator well-being?

5. **System Design**
   - How to design systems that improve metrics AND reduce stress?
   - How to balance optimization with human needs?
   - How to measure success holistically?

**Key Insights:**
- Metrics can be gamed
- Local optimization can hurt the system
- Human factors matter
- Balance is key

