## Simulation

### Manage Disruptions Without Creating Chaos

**Objective:** Practice handling disruptions in a simulated production environment

**Scenario:** You're managing a production line. Disruptions will occur. Your job is to handle them without creating chaos.

**Disruption Types:**
- Machine breakdown (2 hours, critical machine)
- Material shortage (key component delayed 1 day)
- Labor absenteeism (key operator out, no replacement)
- Quality issue (batch needs rework, 4 hours)
- Urgent order (high-priority customer, due today)

**Steps:**

1. **Monitor the System**
   - Track schedule adherence
   - Monitor for disruptions
   - Identify early warning signs
   - Assess disruption impact

2. **Assess the Disruption**
   - What type of disruption?
   - How severe is it?
   - How long will it last?
   - What work is affected?

3. **Decide on Response**
   - Reschedule or wait?
   - Expedite or delay?
   - Reassign or cancel?
   - Local fix or system-wide change?

4. **Execute the Response**
   - Communicate changes
   - Update the schedule
   - Notify affected parties
   - Monitor execution

5. **Evaluate the Outcome**
   - Did the response work?
   - What was the impact?
   - What would you do differently?
   - How to prevent next time?

**Deliverables:**
- Disruption log with responses
- Decision rationale for each disruption
- Impact assessment (throughput, lateness, chaos)
- Lessons learned
- Recommendations for disruption prevention

