# Module 3: Constraint-Based Optimization

**Problem:** Optimizing everything instead of the constraint  
**Capability:** Constraint-Based Optimization  
**Inspiration:** Theory of Constraints, bottleneck management, and optimization

---

## Mindset Shift

> "Optimize the bottleneck, not everything. The system's throughput is limited by its constraint."

---

## Learning Objectives

### Theory of Constraints (TOC)

- **The Five Focusing Steps:**
  1. Identify the constraint
  2. Exploit the constraint
  3. Subordinate everything else to the constraint
  4. Elevate the constraint
  5. Repeat (don't let inertia become the constraint)

- Why optimizing non-constraints doesn't help
- The difference between local and system optimization
- How constraints move and change
- When to break vs. exploit constraints

### Hard vs Soft Constraints

- **Hard constraints:** Physical, cannot be violated (machine capacity, material availability)
- **Soft constraints:** Preferences, can be violated at a cost (preferred sequences, operator preferences)
- How to model each type
- When to relax soft constraints
- The cost of violating constraints
- How to prioritize constraints

### Feasible vs Optimal Solutions

- **Feasible:** Satisfies all hard constraints
- **Optimal:** Best objective value among feasible solutions
- Why feasible is often good enough
- The cost of finding optimal solutions
- When optimal is worth the cost
- How to find good feasible solutions quickly

### Constraint Prioritization

- Which constraints matter most?
- How to identify the true constraint
- When constraints conflict
- How to handle constraint hierarchies
- The cost of constraint violations
- How to communicate constraints to operators

