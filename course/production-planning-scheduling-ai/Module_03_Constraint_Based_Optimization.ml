## Exercise

### Identify and Protect the System Bottleneck

**Objective:** Find the bottleneck and optimize around it

**Steps:**

1. **Map the Production Flow**
   - Identify all resources and operations
   - Map the sequence of operations
   - Document capacity at each step
   - Identify dependencies

2. **Calculate Load vs. Capacity**
   - Calculate demand load at each resource
   - Compare to effective capacity
   - Identify where load exceeds capacity
   - Find the bottleneck

3. **Protect the Bottleneck**
   - Ensure bottleneck is never starved
   - Ensure bottleneck is never blocked
   - Minimize changeovers at bottleneck
   - Prioritize bottleneck work

4. **Subordinate Non-Bottlenecks**
   - Non-bottlenecks should support the bottleneck
   - Don't optimize non-bottlenecks independently
   - Build buffers before the bottleneck
   - Accept idle time at non-bottlenecks

5. **Monitor and Adjust**
   - Track bottleneck utilization
   - Monitor for constraint shifts
   - Adjust when constraint moves
   - Don't let inertia become the constraint

**Deliverables:**
- Production flow map
- Load vs. capacity analysis
- Bottleneck identification
- Bottleneck protection plan
- Subordination strategy for non-bottlenecks
- Monitoring plan for constraint shifts

