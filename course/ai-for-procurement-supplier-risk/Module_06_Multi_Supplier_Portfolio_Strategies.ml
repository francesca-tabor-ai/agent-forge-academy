## Practical Exercise

### Design a Multi-Supplier Portfolio

**Activity:** Build a supplier portfolio optimization model.

**Components:**
1. **Supplier Assessment**
   - Reliability scores
   - Price and cost analysis
   - Risk profiles
   - Capacity constraints
   - Geographic and operational diversity

2. **Portfolio Design**
   - Supplier selection
   - Volume allocation
   - Risk diversification
   - Cost optimization
   - Resilience evaluation

3. **Scenario Analysis**
   - Single supplier failure
   - Multiple supplier failures
   - Market disruption
   - Cost shock scenarios
   - Portfolio performance under stress

4. **Optimization Model**
   - Objective function (cost + risk)
   - Constraints (capacity, quality, etc.)
   - Optimization algorithm
   - Sensitivity analysis
   - Recommendation framework

**Deliverables:**
- Portfolio optimization model (Python)
- Supplier selection and allocation
- Risk analysis results
- Scenario test outcomes
- Portfolio recommendation

**Data Requirements:**
- Supplier performance data
- Cost and pricing data
- Capacity information
- Risk profiles
- Historical disruption data

