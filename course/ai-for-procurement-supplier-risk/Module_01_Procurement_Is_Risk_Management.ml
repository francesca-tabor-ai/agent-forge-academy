## Practical Exercise

### Map a Real Sourcing Decision to Total Cost Components

**Activity:** Take a recent supplier selection decision and break down all cost components.

**Steps:**
1. Identify purchase price
2. Map delivery and logistics costs
3. Quantify quality and defect costs
4. Calculate operational disruption costs
5. Estimate switching and relationship costs
6. Assess risk exposure

**Deliverables:**
- TCO breakdown spreadsheet
- Risk assessment matrix
- Cost component comparison
- Decision framework documentation

### Calculate True Cost of a "Cheap" Supplier

**Exercise:** Use a case study to calculate the true cost when reliability fails.

**Components:**
- Direct cost savings
