# Module 1: Procurement Is Risk Management

**Problem:** Lowest bid wins mentality  
**Capability:** Risk-Aware Procurement Decision Making  
**Inspiration:** Financial risk management frameworks

---

## Mindset Shift

**"Procurement is risk management disguised as cost management."**

---

## What They Learn

### Price vs Total Cost of Ownership (TCO)

- Purchase price vs. lifetime cost
- Hidden costs in supplier selection
- Quality failures as cost multipliers
- Delivery delays and their business impact
- Switching costs and supplier lock-in

### Reliability as a Hidden Cost

- On-time delivery value
- Quality consistency premium
- Communication and relationship costs
- Operational disruption costs
- Reputation and brand risk

### Contractual vs Operational Risk

- Contract terms and legal protection
- Operational reliability gaps
- Performance variance
- Financial stability indicators
- Geopolitical and supply chain risks

### Why "Lowest Bid Wins" Fails

- Price optimization fallacy
- Missing cost components
- Risk externalization
- Short-term thinking traps
- Total cost blindness

