## Case Study

### Supplier Switch That Caused Cascading Failures

**Scenario:** A company switched to a lower-cost supplier that caused production delays, quality issues, and customer dissatisfaction.

**Analysis:**
- Initial cost savings calculation
- Hidden costs that emerged
- Business impact quantification
- Decision point reconstruction
- Lessons for future sourcing

**Discussion Points:**
- When did the true cost become visible?
- What signals were missed?
- How could risk assessment have changed the decision?
- What would a TCO model have shown?

