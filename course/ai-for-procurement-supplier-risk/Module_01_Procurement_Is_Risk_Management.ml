## Key Concepts

### Total Cost of Ownership Framework

- Direct costs (purchase price)
- Indirect costs (logistics, handling)
- Quality costs (defects, rework)
- Operational costs (delays, disruptions)
- Relationship costs (switching, management)
- Risk costs (volatility, exposure)

### Risk Categories in Procurement

- Operational risk (delivery, quality)
- Financial risk (stability, payment terms)
- Strategic risk (dependence, lock-in)
- External risk (geopolitical, supply chain)
- Reputational risk (brand, customer impact)

### Decision Framework

- Multi-criteria evaluation
- Risk-adjusted cost comparison
- Scenario analysis
- Sensitivity testing
- Decision transparency

