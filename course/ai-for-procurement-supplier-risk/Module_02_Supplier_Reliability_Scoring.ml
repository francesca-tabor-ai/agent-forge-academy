## Practical Exercise

### Score Real Suppliers Using Historical Data

**Activity:** Apply the reliability scoring model to actual supplier performance data.

**Steps:**
1. Collect supplier performance data
2. Calculate component scores
3. Compute composite reliability score
4. Rank suppliers by reliability
5. Compare scores to subjective assessments
6. Identify score discrepancies and reasons

**Analysis:**
- Score distribution analysis
- Component contribution analysis
- Supplier segmentation by reliability
- Improvement opportunity identification

