## Hands-On Lab

### Build a Composite Supplier Reliability Score

**Objective:** Create a quantitative reliability scoring system.

**Components:**
1. **Delivery Reliability Score**
   - On-time delivery percentage
   - Lead time variance
   - Delivery accuracy weighting

2. **Quality Reliability Score**
   - Defect rate
   - Quality consistency
   - Rework frequency

3. **Operational Reliability Score**
   - Communication responsiveness
   - Problem resolution time
   - Proactive issue notification

4. **Composite Score Calculation**
   - Weighted combination
   - Normalization techniques
   - Score interpretation

**Deliverables:**
- Reliability scoring algorithm
- Score calculation code (Python)
- Supplier ranking by reliability
- Score interpretation guide

**Data Requirements:**
- Historical delivery data
- Quality metrics
- Communication logs
- Performance records

