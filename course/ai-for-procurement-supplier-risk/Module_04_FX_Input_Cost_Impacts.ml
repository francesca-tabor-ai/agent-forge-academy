## Exercise

### Stress-Test Supplier Costs Under FX Shocks

**Objective:** Build a stress-testing model for currency and commodity shocks.

**Components:**
1. **Exposure Mapping**
   - Supplier currency exposure
   - Commodity input dependencies
   - Cost structure analysis
   - Pass-through mechanisms

2. **Shock Scenario Design**
   - FX shock scenarios (10%, 20%, 30%)
   - Commodity price shock scenarios
   - Combined shock scenarios
   - Historical shock analysis

3. **Cost Impact Calculation**
   - Direct cost impact
   - Pass-through effects
   - Timing impacts
   - Total landed cost changes

4. **Supplier Comparison**
   - Relative exposure ranking
   - Shock resilience scoring
   - Risk-adjusted cost comparison
   - Mitigation strategy evaluation

**Deliverables:**
- FX and commodity exposure model (Python)
- Stress-test results
- Supplier risk ranking
- Mitigation recommendations

**Data Requirements:**
- Supplier cost structures
- Currency exposure data
- Commodity price histories
- FX rate histories
- Contract terms

