# Capstone Project: Supplier Selection and Risk-Monitoring System

**Problem:** Fragmented supplier evaluation and monitoring  
**Capability:** Integrated Supplier Intelligence Platform  
**Inspiration:** End-to-end risk management systems

---

## Project Overview

Build a supplier selection and risk-monitoring system that integrates all course concepts into a practical, deployable solution.

---

## Project Requirements

### Core Components

1. **Supplier Reliability Scoring**
   - On-time delivery metrics
   - Quality and defect rates
   - Lead-time variability
   - Composite reliability score
   - Score visualization

2. **Price Volatility Modeling**
   - Historical price analysis
   - Volatility calculation
   - Price stability scoring
   - Volatility-adjusted price comparison
   - Price forecasting

3. **FX Exposure Analysis**
   - Currency exposure mapping
   - FX pass-through modeling
   - Commodity exposure analysis
   - Stress-testing framework
   - Risk-adjusted cost calculation

4. **Early Warning System**
   - Signal extraction from transactional data
   - Anomaly detection
   - Risk score calculation
   - Alert generation
   - Dashboard visualization

5. **Supplier Ranking Logic**
   - Multi-criteria evaluation
   - Weighted scoring
   - Risk-adjusted ranking
   - Recommendation generation
   - Comparison framework

6. **Risk Thresholds**
   - Threshold definition
   - Risk categorization
   - Alert triggers
   - Action recommendations
   - Escalation logic

7. **Decision Framework**
   - Supplier selection workflow
   - Recommendation presentation
   - Explanation and transparency
   - Override mechanisms
   - Feedback collection

