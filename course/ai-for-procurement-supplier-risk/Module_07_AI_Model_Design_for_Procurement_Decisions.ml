## Role Play

### Defend an AI Supplier Recommendation to Procurement Leadership

**Scenario:** Present an AI-driven supplier recommendation to procurement leadership who are skeptical of the model.

**Preparation:**
- Understand the recommendation
- Prepare explanation of model logic
- Anticipate questions and concerns
- Design visualizations and evidence
- Plan for override scenarios

**Role Play Structure:**
1. Present the recommendation
2. Explain the model and scoring
3. Address questions and concerns
4. Handle override requests
5. Discuss implementation and monitoring

**Learning Objectives:**
- Communication of AI recommendations
- Building trust in AI systems
- Handling skepticism
- Balancing AI and human judgment
- Practical implementation considerations

