## Practical Exercise

### Build a Finance-Ready ROI Presentation

**Objective:** Create a presentation that survives finance scrutiny.

**Components:**

1. **Executive Summary (1 slide)**
   - Investment amount
   - Expected benefit (with range)
   - Payback period
   - Key risks
   - Recommendation

2. **Attribution Logic (2-3 slides)**
   - How AI causes the improvement
   - Experimental design or causal proof
   - Control group and baseline
   - Alternative explanations ruled out

3. **Financial Model (3-4 slides)**
   - Cost breakdown (implementation + operating)
   - Benefit calculation (with assumptions)
   - Payback period and NPV
   - Confidence intervals (best/base/worst case)

4. **Risk Assessment (1-2 slides)**
   - Key risks and mitigation
   - Sensitivity analysis
   - Scenario planning
   - What could go wrong

5. **Implementation Plan (1 slide)**
   - Timeline and milestones
   - Resource requirements
   - Success metrics
   - Next steps

**Deliverables:**
- Finance-ready presentation deck
- Supporting data and evidence
- Confidence interval calculations
- Risk assessment
- Implementation plan

