## Case Study

### ROI Presentation That Survived Finance Scrutiny

**Scenario:** An AI team presented ROI that passed finance review and got funding.

**Analysis:**

1. **The Presentation**
   - Conservative assumptions (80% of best case)
   - Clear attribution logic (difference-in-differences)
   - Confidence intervals (best/base/worst case)
   - Acknowledged limitations upfront
   - Phased approach with quick initial payback

2. **Finance's Response**
   - Accepted attribution logic
   - Trusted conservative assumptions
   - Appreciated confidence intervals
   - Valued honesty about limitations
   - Approved Phase 1 with clear success criteria

3. **Why It Worked**
   - Conservative framing built trust
   - Causal proof, not correlation
   - Clear logic and evidence
   - Honest about uncertainty
   - Phased approach reduced risk

**Lessons:**
- Conservative assumptions build trust
- Causal proof is essential
- Confidence intervals show rigor
- Honesty about limitations is valued
- Phased approaches reduce risk

