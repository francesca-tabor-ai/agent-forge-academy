## Role Play

### Defend AI ROI in a Finance Review

**Objective:** Practice defending ROI in a simulated finance review.

**Setup:**
- Presenter: AI team member with ROI model
- Reviewers: Finance team (CFO, controller, analyst)
- Format: 30-minute presentation + 30-minute Q&A

**Scenario:**
- AI forecasting system
- $500K implementation cost
- $200K annual benefit claim
- 2.5-year payback period
- Finance challenges attribution, assumptions, and timing

**Finance Questions (Typical):**
1. "How do you know AI caused the improvement?"
2. "What was your baseline? How do we know it's comparable?"
3. "What if benefits take longer to realize?"
4. "What are the alternative explanations?"
5. "What's your confidence interval?"
6. "What if adoption is slower than expected?"
7. "How does this compare to alternative investments?"

**Preparation:**
- Anticipate finance questions
- Prepare data and evidence
- Build confidence intervals
- Document assumptions and limitations
- Practice clear, concise answers
- Know when to say "I don't know, but here's how we'll find out"

**Success Criteria:**
- Finance accepts attribution logic
- Conservative assumptions are credible
- Confidence intervals are reasonable
- Limitations are acknowledged
- Next steps are clear

