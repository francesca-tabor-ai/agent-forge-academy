## Exercise

### Build a Payback Timeline for an AI Initiative

**Objective:** Create a realistic payback timeline that finance will trust.

**Steps:**

1. **Map Implementation Costs**
   - Upfront development costs
   - Integration and deployment costs
   - Training and change management costs
   - Ongoing operating costs
   - Document cost timing (when costs occur)

2. **Estimate Benefit Ramp-Up**
   - When benefits start (not immediately)
   - Ramp-up curve (linear, exponential, S-curve)
   - Time to full benefit realization
   - Adoption and learning curve effects
   - Model realistic benefit timing

3. **Calculate Payback Period**
   - Cumulative costs over time
   - Cumulative benefits over time
   - Payback point: when benefits exceed costs
   - Net present value (NPV) calculation
   - Internal rate of return (IRR) if applicable

4. **Build Risk-Adjusted Model**
   - Best case scenario (fast ramp-up, high benefits)
   - Base case scenario (realistic assumptions)
   - Worst case scenario (slow ramp-up, low benefits)
   - Probability-weighted expected value
   - Confidence intervals

5. **Create Executive Timeline**
   - Month-by-month cost and benefit projection
   - Payback period highlighted
   - Key milestones and decision points
   - Risk factors and mitigation
   - Finance-ready presentation

**Deliverables:**
- Implementation cost breakdown
- Benefit ramp-up model
- Payback period calculation
- Risk-adjusted ROI model
- Executive timeline
- Finance-ready summary

### Example Calculation

**Scenario:**
- Implementation cost: $500K (month 0)
- Operating cost: $50K/year (ongoing)
- Benefit starts: Month 3 (ramp-up period)
- Benefit ramp-up: 25% month 3, 50% month 4, 75% month 5, 100% month 6+
- Annual benefit: $200K/year (at full scale)

**Calculation:**
- Month 3: -$500K (cost) + $4.2K (benefit) = -$495.8K cumulative
- Month 6: -$500K + $12.5K (3 months partial) = -$487.5K cumulative
- Month 12: -$500K - $50K (operating) + $150K (9 months full benefit) = -$400K
- Month 18: -$500K - $75K + $275K = -$300K
- Month 24: -$500K - $100K + $400K = -$200K
- Month 30: -$500K - $125K + $525K = -$100K
- Month 36: -$500K - $150K + $650K = $0 (payback)
- **Payback period: 36 months (3 years)**

