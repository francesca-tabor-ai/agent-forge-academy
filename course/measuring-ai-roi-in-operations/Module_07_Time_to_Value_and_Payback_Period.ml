## Case Study

### Long Payback Period That Didn't Get Funded

**Scenario:** An AI system promised $1M annual benefit but had a 5-year payback period. Finance rejected it.

**Analysis:**

1. **The Proposal**
   - $2M implementation cost
   - $200K annual operating cost
   - $1M annual benefit
   - 5-year payback period

2. **Finance's Concerns**
   - Too long payback period (target: <2 years)
   - High upfront risk
   - Uncertain benefit realization
   - Alternative investments with faster payback

3. **The Solution: Phased Approach**
   - Phase 1: $500K investment, $200K annual benefit, 2.5-year payback
   - Phase 2: Additional $1.5M if Phase 1 succeeds
   - Reduced risk, faster initial payback
   - Finance approved Phase 1

4. **Why It Worked**
   - Smaller initial investment
   - Faster payback period
   - Proof of concept before full commitment
   - Reduced risk for finance

**Lessons:**
- Structure phased rollouts for faster initial payback
- Start small to prove value before scaling
- Finance prefers incremental investments
- Quick wins build credibility for bigger investments

