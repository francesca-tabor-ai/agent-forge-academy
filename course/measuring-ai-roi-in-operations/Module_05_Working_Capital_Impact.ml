## Case Study

### Working Capital Improvement That Finance Ignored

**Scenario:** A company reduced inventory by 20% through better forecasting, but finance didn't see the value.

**Analysis:**

1. **The Claim**
   - 20% inventory reduction
   - $2M in working capital freed
   - Operations team reported success

2. **Finance's Questions**
   - Did working capital actually decrease, or just shift?
   - What was the cost of achieving this reduction?
   - Is this sustainable or temporary?
   - Did service level suffer?

3. **The Reality**
   - Inventory decreased, but receivables increased (customers took longer to pay)
   - Total working capital unchanged
   - Service level dropped, causing stockouts
   - Forecasting system cost $500K
   - No net cash benefit

4. **Why It Failed**
   - Measured one component, not total working capital
   - Ignored shifts between components
   - Didn't account for service level trade-offs
   - No proof of actual cash impact

**Lessons:**
- Measure total working capital, not individual components
- Account for shifts between components
- Include service level trade-offs
- Prove actual cash impact, not just component changes

