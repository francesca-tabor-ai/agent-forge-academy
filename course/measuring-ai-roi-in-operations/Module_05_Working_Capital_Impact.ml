## Hands-On Exercise

### Build a Working Capital Impact Model

**Objective:** Create a model that quantifies how AI improvements affect working capital and cash flow.

**Steps:**

1. **Establish Baseline Working Capital**
   - Current inventory value
   - Accounts receivable balance
   - Accounts payable balance
   - Calculate DSO, DIO, DPO
   - Calculate cash conversion cycle
   - Document baseline cash flow

2. **Estimate AI-Driven Improvements**
   - Inventory optimization reducing DIO
   - Better forecasting reducing inventory
   - Payment optimization affecting DPO
   - Credit management affecting DSO
   - Quantify expected improvements

3. **Calculate Working Capital Impact**
   - New inventory value
   - New receivables balance
   - New payables balance
   - Working capital freed = Baseline - New
   - Annual cash flow impact

4. **Account for FX and Inflation**
   - Adjust for currency effects
   - Adjust for inflation
   - Constant currency analysis
   - Real vs nominal impact

5. **Model Predictability Value**
   - Baseline working capital volatility
   - Improved predictability from AI
   - Risk reduction value
   - Lower cost of capital benefit

6. **Build Complete Model**
   - Working capital reduction value
   - Cash flow improvement
   - Predictability value
   - Confidence intervals and sensitivity analysis

**Deliverables:**
- Working capital baseline documentation
- Cash conversion cycle calculation
- Working capital impact model
- FX and inflation adjustments
- Predictability value assessment
- Executive-ready summary

### Example Calculation

**Scenario:**
- Current inventory: $10M (DIO = 60 days)
- Current receivables: $5M (DSO = 30 days)
- Current payables: $3M (DPO = 20 days)
- Cash conversion cycle: 60 + 30 - 20 = 70 days
- AI improvement: 10% inventory reduction, 5% DSO reduction
- WACC: 8%

**Calculation:**
- New inventory: $9M (DIO = 54 days)
- New receivables: $4.75M (DSO = 28.5 days)
- Working capital freed: $1.25M
- Annual cost savings: $1.25M × 8% = $100K
- New cash conversion cycle: 54 + 28.5 - 20 = 62.5 days
- Cash flow improvement: 7.5 days faster conversion

