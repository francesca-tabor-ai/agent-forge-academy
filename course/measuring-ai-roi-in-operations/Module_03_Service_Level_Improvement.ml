## Case Study

### Service Improvement That Didn't Create Value

**Scenario:** A company improved OTIF from 85% to 95% through better routing AI, but couldn't prove revenue impact.

**Analysis:**

1. **The Claim**
   - 10% OTIF improvement
   - Operations team reported "better customer satisfaction"
   - No revenue impact documented

2. **Finance's Questions**
   - Did revenue actually increase?
   - Did customer retention improve?
   - What was the cost of the improvement?
   - Could the same result be achieved cheaper?

3. **The Reality**
   - OTIF improved, but customers didn't notice (already had workarounds)
   - No measurable revenue increase
   - Routing system cost $300K to implement
   - Operating costs increased (more expensive routes)
   - Net negative ROI

4. **Why It Failed**
   - Measured operational metric, not revenue impact
   - No customer behavior change
   - Didn't account for implementation and operating costs
   - No proof of value creation

**Lessons:**
- Service improvements must translate to customer behavior change
- Revenue impact must be measured, not assumed
- Implementation and operating costs must be included
- Customer workarounds can hide service problems

