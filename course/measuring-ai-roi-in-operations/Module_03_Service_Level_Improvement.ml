## Exercise

### Model Revenue Impact of Service Improvements

**Objective:** Quantify how service level improvements translate to revenue.

**Steps:**

1. **Establish Baseline Service Metrics**
   - Current OTIF, fill rate, backorder rate
   - Historical service level trends
   - Customer complaints and churn related to service
   - Document baseline revenue and customer base

2. **Estimate AI-Driven Service Improvement**
   - Forecast accuracy improvement reducing stockouts
   - Better routing reducing delivery delays
   - Inventory optimization improving fill rates
   - Quantify expected service level improvement (%)

3. **Calculate Revenue Protection**
   - Estimate lost sales from current service failures
   - Calculate revenue recovered from improved service
   - Model customer churn reduction
   - Quantify reputation and future revenue impact

4. **Model Revenue Growth (If Applicable)**
   - Service improvements enabling new customer acquisition
   - Higher service levels allowing premium pricing
   - Market share gains from superior service
   - Quantify growth opportunity (if any)

5. **Build Revenue Impact Model**
   - Revenue protection value
   - Revenue growth value (if applicable)
   - Customer lifetime value impact
   - Confidence intervals and sensitivity analysis

**Deliverables:**
- Service level baseline documentation
- Revenue impact model
- Revenue protection calculation
- Revenue growth opportunity assessment (if applicable)
- Customer lifetime value impact
- Executive-ready summary

### Example Calculation

**Scenario:**
- Current fill rate: 92%
- Lost sales from 8% stockouts: $500K/year
- Customer churn from poor service: 5% of affected customers
- Average customer lifetime value: $10K
- AI improvement: 3% fill rate increase (to 95%)

**Calculation:**
- Revenue protection: 3% × $500K = $15K/year (direct)
- Churn reduction: 3% × 5% × 100 customers × $10K = $15K/year
- Total revenue impact: $30K/year
- If service improvement enables 2% price premium: Additional $100K/year

