## Hands-On Exercise

### Convert Inventory Reduction into Working Capital Impact

**Objective:** Calculate the financial value of inventory improvements.

**Steps:**

1. **Calculate Current Inventory Turns**
   - Gather inventory value and cost of goods sold (COGS)
   - Calculate annual turns: COGS / Average Inventory
   - Calculate days of inventory: 365 / Turns
   - Document baseline metrics

2. **Estimate AI-Driven Improvement**
   - Forecast accuracy improvement
   - Safety stock reduction
   - Lead time optimization
   - Quantify expected inventory reduction (%)

3. **Calculate Working Capital Impact**
   - New inventory value = Current × (1 - Reduction %)
   - Working capital freed = Current - New
   - Annual cost of capital = Working Capital Freed × WACC
   - Present value of multi-year impact

4. **Account for Service Level Risk**
   - Estimate stockout probability increase
   - Calculate cost of lost sales
   - Net value = Working Capital Benefit - Stockout Cost
   - Sensitivity analysis on assumptions

5. **Build Confidence Intervals**
   - Best case, base case, worst case scenarios
   - Probability-weighted expected value
   - Risk-adjusted ROI calculation

**Deliverables:**
- Inventory turns calculation spreadsheet
- Working capital impact model
- Cost of capital calculation
- Service level risk assessment
- Confidence intervals and sensitivity analysis
- Executive-ready summary

### Example Calculation

**Scenario:**
- Current inventory: $10M
- COGS: $50M/year
- Current turns: 5x
- AI improvement: 10% inventory reduction
- WACC: 8%

**Calculation:**
- New inventory: $9M
- Working capital freed: $1M
- Annual cost savings: $1M × 8% = $80K
- If service level risk costs $20K: Net benefit = $60K/year

