## Case Study

### Inventory Reduction That Didn't Create Value

**Scenario:** A company reduced inventory by 15% through better forecasting, but finance didn't see the value.

**Analysis:**

1. **The Claim**
   - 15% inventory reduction
   - $1.5M in working capital freed
   - Operations team celebrated

2. **Finance's Questions**
   - Did inventory actually decrease, or just shift between locations?
   - What was the cost of achieving this reduction?
   - Did service level suffer?
   - Is this sustainable or temporary?

3. **The Reality**
   - Inventory shifted from warehouses to in-transit
   - Total network inventory unchanged
   - Service level dropped, causing $200K in lost sales
   - Forecasting system cost $500K to implement
   - Net negative ROI

4. **Why It Failed**
   - Measured local, not network-level impact
   - Ignored service level trade-offs
   - Didn't account for implementation cost
   - No attribution to actual cash impact

**Lessons:**
- Measure network-level inventory, not just location-level
- Account for service level costs
- Include implementation and operating costs
- Prove actual cash impact, not just inventory movement

