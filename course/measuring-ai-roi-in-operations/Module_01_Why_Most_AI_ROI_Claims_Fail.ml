## Case Study

### AI Project Praised by Ops, Rejected by Finance

**Scenario:** An AI forecasting system showed 15% accuracy improvement in a pilot. Operations team was enthusiastic. Finance rejected the business case.

**Analysis:**

1. **The Claim**
   - 15% forecast accuracy improvement
   - Operations team reported "better decisions"
   - Pilot site showed inventory reduction

2. **Finance's Questions**
   - What was the baseline accuracy?
   - Did inventory actually decrease, or just shift?
   - What was the cost of the improvement?
   - Could the same result be achieved cheaper?
   - What's the confidence interval on the 15%?

3. **The Reality**
   - Baseline was already poor (60% accuracy)
   - 15% improvement = 69% accuracy (still poor)
   - Inventory reduction was seasonal, not AI-driven
   - Pilot required 3x manual effort to validate
   - No attribution to actual business outcomes

4. **Why It Failed**
   - Vanity metric (accuracy) without value linkage
   - No causal proof of business impact
   - Pilot conditions didn't represent reality
   - Cost-benefit didn't justify investment

**Discussion Points:**
- What metrics would finance have accepted?
- How could attribution have been established?
- What would a defensible business case look like?
- Why did operations see value but finance didn't?

