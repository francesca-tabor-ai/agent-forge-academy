## Practical Exercise

### Audit Your AI ROI Claims

**Objective:** Identify vanity metrics and attribution gaps in your AI initiatives.

**Steps:**

1. **List Your AI ROI Claims**
   - Document all metrics you've used to justify AI
   - Identify which are technical vs business metrics
   - Note any correlation claims vs causation proof

2. **Finance Readiness Test**
   - Would a CFO accept this metric?
   - Can you prove AI caused the improvement?
   - What's the confidence interval?
   - What are the alternative explanations?

3. **Attribution Audit**
   - What else changed at the same time?
   - Could external factors explain the improvement?
   - Is there a control group?
   - What's the counterfactual?

4. **Value Linkage Check**
   - Does this metric link to cash, profit, or working capital?
   - How does this improvement translate to financial impact?
   - What's the cost of achieving this improvement?
   - Is there a cheaper way to get the same result?

**Deliverables:**
- ROI claim audit spreadsheet
- Vanity metrics identified and flagged
- Attribution gaps documented
- Finance readiness assessment
- Revised ROI claims with value linkage

### Convert Vanity Metrics to Value Metrics

**Exercise:** Take a technical metric and trace it to financial impact.

**Example:**
- Vanity: "Model accuracy improved 20%"
- Value: "Reduced forecast error by 20%, enabling 15% inventory reduction, freeing $2M in working capital"

**Components:**
- Start with technical metric
- Identify decision it enables
- Quantify operational impact
- Calculate financial value
- Document assumptions and confidence

