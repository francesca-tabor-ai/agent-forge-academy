## Evaluation Criteria

### Financial Rigor (30%)

- Accurate cost and benefit calculations
- Proper working capital and cash flow modeling
- Realistic ramp-up curves
- Confidence intervals and sensitivity analysis
- Risk-adjusted ROI

### Conservative Assumptions (25%)

- Assumptions that are realistic, not optimistic
- Conservative benefit estimates
- Realistic cost estimates
- Honest about uncertainty
- Underpromise, overdeliver framing

### Clarity (20%)

- Clear logic and calculations
- Easy to follow presentation
- Well-organized documentation
- Executive-ready format
- Finance-friendly language

### Credibility with Finance (25%)

- Attribution logic that proves causality
- Control groups and baselines that are comparable
- Alternative explanations considered and ruled out
- Limitations acknowledged
- Confidence intervals that show rigor

