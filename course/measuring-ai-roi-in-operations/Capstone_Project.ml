## Example Project Structure

### Forecasting System ROI Model

**System:** AI demand forecasting for inventory optimization

**ROI Model:**
- Implementation: $500K
- Operating: $100K/year
- Benefit: 10% inventory reduction = $1M working capital freed
- Annual savings: $1M × 8% WACC = $80K/year
- Service level improvement: $50K revenue protection
- Total benefit: $130K/year
- Payback: 3.8 years

**Attribution:**
- Difference-in-differences design
- 10 treated locations, 10 control locations
- 6-month pre/post analysis
- Proved 8% inventory reduction (causal)
- Ruled out seasonality, market changes, other initiatives

**Confidence Intervals:**
- Best case: 12% reduction, 3-year payback
- Base case: 10% reduction, 3.8-year payback
- Worst case: 6% reduction, 6-year payback

**Presentation:**
- Executive summary with conservative base case
- Attribution logic with experimental design
- Financial model with confidence intervals
- Risk assessment and mitigation
- Phased rollout plan

