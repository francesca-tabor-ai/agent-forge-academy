# Capstone Project: Build a Complete ROI Model

**Problem:** AI teams need to prove value to get funding and scale  
**Capability:** Complete ROI Model Development  
**Inspiration:** Finance business case development

---

## Project Overview

Build a complete, finance-ready ROI model for a real or simulated AI system. This project integrates all course concepts into a single, defensible business case.

---

## Project Requirements

### Choose Your AI System

Select one of the following (or propose your own):

1. **Forecasting System**
   - Demand forecasting, inventory forecasting, or sales forecasting
   - Focus on inventory turns and working capital impact

2. **Inventory Optimization**
   - Multi-echelon inventory, safety stock optimization, or SKU-level optimization
   - Focus on working capital and service level trade-offs

3. **Routing Optimization**
   - Logistics routing, delivery optimization, or network optimization
   - Focus on cost-to-serve and service level improvement

4. **Your Own AI System**
   - Any AI system you've deployed or plan to deploy
   - Must have operational impact that can be quantified

---

## Deliverables

### 1. ROI Model

Build a complete financial model that includes:

- **Cost Model**
  - Implementation costs (development, integration, deployment)
  - Operating costs (maintenance, infrastructure, support)
  - Cost timing and cash flow

- **Benefit Model**
  - Working capital impact (inventory, receivables, payables)
  - Revenue impact (protection and/or growth)
  - Cost-to-serve impact (logistics, handling, storage)
  - Service level impact (if applicable)
  - Benefit timing and ramp-up curve

- **Financial Metrics**
  - Payback period
  - Net present value (NPV)
  - Internal rate of return (IRR) if applicable
  - Confidence intervals (best/base/worst case)
  - Risk-adjusted ROI

### 2. Attribution Logic

Document how you prove AI caused the improvement:

- **Experimental Design**
  - A/B test, quasi-experiment, or before/after (with limitations)
  - Control group selection and validation
  - Baseline definition and comparability

- **Causal Proof**
  - How you rule out alternative explanations
  - Confounding variables considered
  - External factors accounted for
  - Why correlation is not enough

- **Confidence Assessment**
  - Confidence intervals for key metrics
  - Sensitivity analysis
  - Scenario planning
  - Limitations and assumptions

### 3. Executive-Ready Narrative

Create a presentation that survives finance scrutiny:

- **Executive Summary**
  - Investment amount and payback period
  - Expected benefit with confidence intervals
  - Key risks and mitigation
  - Clear recommendation

- **Attribution Story**
  - How AI causes the improvement
  - Causal proof, not correlation
  - Control group and baseline
  - Alternative explanations ruled out

- **Financial Story**
  - Conservative assumptions
  - Confidence intervals
  - Risk assessment
  - Phased approach (if applicable)

- **Implementation Story**
  - Timeline and milestones
  - Resource requirements
  - Success metrics
  - Next steps

