## Case Study

### Cost Reduction That Didn't Improve Profit

**Scenario:** A company reduced logistics costs by 15% through route optimization, but profit didn't improve.

**Analysis:**

1. **The Claim**
   - 15% logistics cost reduction
   - $300K in annual savings
   - Operations team celebrated

2. **Finance's Questions**
   - Did profit actually improve?
   - What costs increased?
   - Were the cost reductions real or just reallocated?

3. **The Reality**
   - Logistics costs decreased, but handling costs increased (longer routes)
   - Service level dropped, causing $100K in lost sales
   - Fixed costs didn't actually decrease (warehouses still needed)
   - Net profit impact: $300K - $100K = $200K (not $300K)
   - Implementation cost: $250K
   - Payback period: 1.25 years (marginal, not compelling)

4. **Why It Failed**
   - Measured one cost component, not total cost-to-serve
   - Ignored revenue impact of service changes
   - Misclassified fixed vs variable costs
   - Didn't account for cost shifts between components

**Lessons:**
- Measure total cost-to-serve, not individual components
- Account for revenue impact of cost changes
- Correctly classify fixed vs variable costs
- Model profit impact, not just cost reduction

