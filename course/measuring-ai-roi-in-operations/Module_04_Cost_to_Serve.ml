## Lab

### Attribute Cost-to-Serve Changes to AI Decisions

**Objective:** Build a model that accurately attributes cost changes to AI decisions.

**Steps:**

1. **Map Cost-to-Serve Components**
   - Logistics: transportation, routing, delivery
   - Handling: picking, packing, processing
   - Storage: warehouse, inventory holding
   - Expediting: rush orders, special handling
   - Document baseline costs for each component

2. **Classify Fixed vs Variable Costs**
   - Identify truly fixed costs (don't change with volume)
   - Identify variable costs (change with volume)
   - Identify semi-variable costs (step functions)
   - Understand cost behavior for accurate attribution

3. **Estimate AI-Driven Cost Changes**
   - Route optimization reducing logistics costs
   - Better forecasting reducing expediting
   - Inventory optimization reducing storage
   - Quantify expected cost reduction per component

4. **Calculate Marginal Cost Impact**
   - Focus on variable cost reductions
   - Calculate marginal cost savings per unit
   - Model volume impact on total savings
   - Avoid attributing fixed cost "savings" that don't materialize

5. **Model Profit Impact**
   - Cost reduction impact
   - Revenue impact (if any)
   - Net profit improvement
   - Confidence intervals and sensitivity analysis

**Deliverables:**
- Cost-to-serve component mapping
- Fixed vs variable cost classification
- Marginal cost calculation model
- AI attribution logic
- Profit impact model
- Executive-ready summary

### Example Calculation

**Scenario:**
- Current logistics cost: $2M/year (60% variable, 40% fixed)
- AI route optimization: 10% variable cost reduction
- Variable logistics cost: $1.2M
- Savings: $120K/year (not $200K, because fixed costs don't change)
- If service improvement increases revenue by $50K: Net profit impact = $170K/year

