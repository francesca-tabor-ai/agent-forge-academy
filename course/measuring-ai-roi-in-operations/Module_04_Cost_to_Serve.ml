### Success Indicators

- **Profit-first thinking**
  - Questions about profit impact come before cost reduction
  - Understanding that cost reduction ≠ value unless profit improves

- **Total cost awareness**
  - Recognition that reducing one cost can increase another
  - Questions about cost shifts and reallocation

- **Fixed vs variable discipline**
  - Understanding that fixed cost "savings" often don't materialize
  - Focus on variable cost reductions that actually improve profit

- **Marginal cost focus**
  - Recognition that marginal cost matters for decisions
  - Calculations that focus on incremental impact

