# Module 7: Measuring Trust & Adoption

**Problem:** Teams measure model accuracy but miss trust and adoption signals  
**Capability:** Trust and Adoption Metrics  
**Inspiration:** Product analytics and behavioral metrics

---

## Mindset Shift

> "If operators don't use it, accuracy doesn't matter."

---

## Learning Objectives

### Override Rates Over Time

- **Healthy override rate:** Operators override when they have better information
  - Indicates: System is used, operators feel in control
  - Pattern: Override rate stabilizes as system improves

- **Unhealthy override rate:** Operators override because they don't trust system
  - Indicates: System recommendations aren't trusted
  - Pattern: Override rate increases or stays high

- **No overrides:** Operators never override
  - Indicates: Either perfect system (rare) or operators not using it
  - Pattern: Need to investigate why no overrides

- How to interpret override rates
- What override patterns indicate trust vs. distrust
- Using override rates to measure system health

### Recommendation Follow-Through

- **Follow-through rate:** How often operators act on recommendations
  - High follow-through: Operators trust recommendations
  - Low follow-through: Operators don't trust or don't see value

- **Time-to-action:** How quickly operators act on recommendations
  - Fast action: High trust, clear value
  - Slow action: Low trust, unclear value, competing priorities

- **Action completion:** Do operators complete recommended actions?
  - Partial completion: Recommendations may be too complex
  - Abandonment: Recommendations don't match operator needs

- How to measure and interpret follow-through
- What follow-through patterns indicate about trust

### Time-to-Decision

- **Before AI:** How long did operators take to make decisions?
- **With AI:** How long do operators take with AI recommendations?
- **AI impact:** Does AI speed up or slow down decisions?

- When faster is better: Routine decisions, high-volume operations
- When slower is acceptable: Complex decisions, high-risk situations
- When slower is a problem: AI adds friction, reduces trust

- How to measure time-to-decision
- What time-to-decision indicates about AI value

### Trust Leading Indicators

- **Early signals:** What behaviors indicate trust before it's explicit?
  - Operators use system without being prompted
  - Operators reference system in discussions
  - Operators defend system recommendations
  - Operators request more AI features

- **Warning signals:** What behaviors indicate distrust?
  - Operators avoid using system
  - Operators create workarounds
  - Operators complain about system
  - Operators disable alerts or features

- How to identify and track leading indicators
- How to act on early signals before trust is lost

