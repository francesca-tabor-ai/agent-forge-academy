## Discussion

### When High Usage Hides Low Trust

**Scenario Analysis:**

1. **The Mandatory System**
   - High usage: Operators must use system (mandated)
   - Low trust: Operators use it but don't trust it
   - Signals: High override rate, low follow-through, complaints
   - Lesson: Usage ≠ trust

2. **The Only Option**
   - High usage: No alternative to AI system
   - Low trust: Operators use it because they have to
   - Signals: Workarounds, manual processes, frustration
   - Lesson: Usage ≠ value

3. **The Silent Abandonment**
   - High usage: System shows high usage metrics
   - Low trust: Operators use it minimally, ignore outputs
   - Signals: Low follow-through, high override, no engagement
   - Lesson: Usage metrics can be misleading

**Discussion Questions:**
- How do you distinguish high usage from high trust?
- What metrics reveal trust vs. just usage?
- When is high usage actually a warning sign?
- How do you measure trust when usage is mandatory?

