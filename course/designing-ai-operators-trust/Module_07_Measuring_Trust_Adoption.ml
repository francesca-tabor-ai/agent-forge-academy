## Key Concepts

### Trust Metrics

- **Override rate:** How often operators override (and why)
- **Follow-through:** How often operators act on recommendations
- **Time-to-decision:** How AI affects decision speed
- **Engagement:** How operators interact with system

### Adoption Metrics

- **Active usage:** Who uses, how often, which features
- **Retention:** Do operators keep using over time
- **Expansion:** Do operators use more features
- **Value realization:** Do operators achieve outcomes

### Warning Signals

- **Trust erosion:** Override rate increasing, follow-through decreasing
- **Adoption risk:** Usage declining, workarounds increasing
- **Silent failure:** Metrics look good but operators don't trust
- **Early indicators:** Engagement dropping, complaints increasing

