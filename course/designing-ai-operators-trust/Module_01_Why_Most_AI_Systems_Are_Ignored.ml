## Key Concepts

### The Adoption Gap

- Technical performance vs. operational adoption
- Demo metrics vs. production usage
- Model accuracy vs. operator trust
- System capability vs. operator willingness

### Trust Dynamics

- Trust is built slowly and destroyed quickly
- One failure can outweigh many successes
- Operators need control, not just accuracy
- Context matters more than correctness

### Organizational Barriers

- Incentive misalignment
- Risk asymmetry (operator bears cost of AI mistakes)
- Cultural resistance to automation
- Workflow integration failures

