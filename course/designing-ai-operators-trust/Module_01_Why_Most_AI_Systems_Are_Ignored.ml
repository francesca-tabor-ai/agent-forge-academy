## Behaviour Installed

### Success Indicators

- **Adoption-first thinking**
  - Questions about usage come before questions about accuracy
  - Recognition that unused systems are failed systems

- **Operator empathy**
  - Understanding of operator incentives and constraints
  - Awareness of trust dynamics and risk perception

- **Early warning awareness**
  - Ability to spot adoption blockers before they become failures
  - Recognition of signals that indicate trust issues

