## Case Review

### AI Tool That Was Accurate But Unused

**Scenario:** Analyze a real AI system with high accuracy but low adoption

**Case Study Framework:**

1. **The System**
   - What the AI was designed to do
   - Technical performance metrics
   - Demo results and pilot outcomes

2. **The Reality**
   - Actual usage rates in production
   - Operator behavior and workarounds
   - Where operators went instead

3. **The Gap**
   - Why accuracy didn't translate to trust
   - What operators needed that the system didn't provide
   - The moment trust was lost (if it was ever gained)

4. **The Lessons**
   - What would have changed adoption
   - Signals that were missed
   - Design decisions that blocked usage

**Discussion Questions:**
- What made operators ignore accurate recommendations?
- When did trust break down?
- What would operators have needed to use it?
- How could the system have been designed differently?

