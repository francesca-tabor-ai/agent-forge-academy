## Learning Objectives

### Demo Success vs Production Failure

- Why demos showcase accuracy but hide adoption barriers
- The gap between model performance and operator trust
- When "good enough" accuracy still fails to get used
- The difference between technical success and operational success
- Why pilot programs mislead about real adoption

### Mismatch Between Model Outputs and Human Decisions

- When model recommendations conflict with operator intuition
- The cost of ignoring domain expertise
- Why "correct" predictions feel wrong to operators
- Context that models miss but humans see
- The trust gap when outputs don't match mental models

### Organizational Incentives

- Why operators avoid using systems that might make them look bad
- The risk of being wrong when following AI recommendations
- When operators are penalized for AI mistakes
- Incentive misalignment between accuracy metrics and operator goals
- How organizational culture blocks AI adoption

### The Cost of Being Wrong Once

- Why one failure destroys trust permanently
- The asymmetry between trust building and trust destruction
- How operators learn to avoid systems after single failures
- The difference between academic error rates and operational impact
- Why "99% accurate" isn't good enough when 1% failures are catastrophic

