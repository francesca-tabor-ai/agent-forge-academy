## Practical Exercise

### Map Your Own AI Adoption Failure

**Objective:** Identify why an AI system you've built or seen wasn't adopted

**Steps:**

1. **Select a System**
   - Choose an AI tool that had low adoption despite good metrics
   - Document its technical performance

2. **Interview Operators (or Role Play)**
   - Why didn't they use it?
   - What would they have needed?
   - When did they lose trust?
   - What workarounds did they create?

3. **Identify Adoption Blockers**
   - Technical: accuracy, latency, reliability
   - Trust: explainability, control, override capability
   - Workflow: integration, timing, context
   - Organizational: incentives, culture, risk

4. **Design the Fix**
   - What would have changed adoption?
   - What signals were available but ignored?
   - How could you have detected the problem earlier?

**Deliverables:**
- Adoption blocker map
- Trust breakdown timeline
- Redesign recommendations
- Early warning signals to monitor

