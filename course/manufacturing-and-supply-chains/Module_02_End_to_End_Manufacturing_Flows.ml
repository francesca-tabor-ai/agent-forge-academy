## Case Study

### Beverage Manufacturing Network (Plants, Depots, Distributors)

**Scenario:** A beverage company with multiple manufacturing plants, regional depots, and local distributors

**System Components:**
- **Plants:** Centralized production facilities
- **Depots:** Regional storage and distribution hubs
- **Distributors:** Local delivery to retailers
- **Retailers:** End customers (stores, restaurants)

**Key Challenges:**
1. **Demand Variability:** Seasonal patterns, promotions, weather
2. **Capacity Constraints:** Production lines, warehouse space, truck capacity
3. **Lead Times:** Production cycles, transportation times, order processing
4. **Information Flow:** Forecasts, orders, inventory levels, sales data

**Analysis Questions:**
- How does a promotion at retail affect production planning?
- What happens when one depot runs out of stock?
- How do transportation delays impact inventory levels?
- Where do forecast errors amplify?
- How do batch sizes at production affect downstream inventory?

**Learning Points:**
- Decisions at one stage ripple through the system
- Local optimization (e.g., minimizing production costs) can create system-wide problems
- Information delays create physical problems
- Capacity constraints at one point constrain the entire system
- Understanding the full flow is essential for good modeling

