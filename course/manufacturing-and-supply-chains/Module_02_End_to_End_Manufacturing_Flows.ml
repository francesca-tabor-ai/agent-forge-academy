## Practical Exercise

### Trace a Decision Through the System

**Objective:** See how a single decision propagates through the manufacturing flow

**Activity:**
1. Start with a decision (e.g., "Increase production batch size by 50%")
2. Trace the impact:
   - Immediate effects (production stage)
   - Downstream effects (warehousing, distribution)
   - Upstream effects (procurement, suppliers)
   - Information flow impacts (forecasts, orders)
3. Identify unintended consequences
4. Document the time delays between cause and effect

**Deliverables:**
- Decision impact map
- Timeline of effects (immediate, short-term, long-term)
- List of unintended consequences
- Identification of where the decision breaks assumptions

