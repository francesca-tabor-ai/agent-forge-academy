## Practical Exercise

### Map a Real Product's Supply Chain (From Raw Material to Shelf)

**Objective:** Build a physical understanding of a real supply chain

**Steps:**

1. **Choose a Product**
   - Select a physical product you can trace
   - Examples: coffee, smartphone, t-shirt, bicycle

2. **Trace Material Flow**
   - Identify raw materials and their origins
   - Map transformation steps (manufacturing, assembly)
   - Document transportation modes and routes
   - Identify storage points (warehouses, distribution centers)
   - Track final delivery to end customer

3. **Map Information Flow**
   - Where do orders originate?
   - How does demand signal propagate upstream?
   - What information is shared between stages?
   - Where are forecasts created and used?
   - Identify information delays and gaps

4. **Document Money Flow**
   - Payment terms at each stage
   - When money changes hands vs. when goods move
   - Working capital requirements
   - Financial incentives and penalties

5. **Identify Physical Constraints**
   - Capacity limits (production, storage, transportation)
   - Lead times (fixed vs. variable)
   - Geographic constraints
   - Regulatory or customs delays

**Deliverables:**
- Visual map showing material, information, and money flows
- List of physical constraints that would break a naïve model
- Identification of where latency matters more than accuracy
- Documentation of one "surprising" constraint you discovered

