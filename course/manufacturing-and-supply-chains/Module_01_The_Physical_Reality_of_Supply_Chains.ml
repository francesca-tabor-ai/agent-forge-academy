# Module 1: The Physical Reality of Supply Chains

**Problem:** Naïve modeling of supply chains as abstract networks  
**Capability:** Physical Systems Understanding  
**Inspiration:** Operations research and logistics engineering

---

## Mindset Shift

> "Supply chains are physical systems with material, information, and money flows — not abstract graphs to optimize."

---

## Learning Objectives

### What a Supply Chain Really Is (Flows, Not Nodes)

- Material flow: physical movement of goods
- Information flow: orders, forecasts, status updates
- Money flow: payments, working capital, cash conversion cycles
- Why nodes matter less than the flows between them
- The difference between network topology and operational reality

### Material Flow vs Information Flow

- Material flow: constrained by physics, capacity, and geography
- Information flow: can be instant but often isn't
- The critical gap between what information says and what material does
- Why information delays create physical problems
- Decoupling points and where information replaces inventory

### Money Flow and Working Capital

- How money moves through supply chains
- Working capital as a constraint
- Payment terms and their impact on operations
- Cash conversion cycles
- Why financial flows determine operational decisions

### Why Latency Matters More Than Accuracy

- The cost of being wrong vs. being late
- Why fast, approximate decisions beat slow, perfect ones
- Information latency cascades into physical delays
- Real-time vs. batch processing in operations
- When "good enough now" beats "perfect later"

