## Key Concepts

### Flow-Based Thinking

- Material flow: what moves, when, and how
- Information flow: signals, delays, and distortions
- Money flow: payments, terms, and working capital
- The interaction between all three flows

### Physical Constraints

- Capacity limits (production, storage, transportation)
- Lead times (fixed vs. variable)
- Geographic and regulatory constraints
- Working capital as an operational constraint

### Latency vs. Accuracy Trade-offs

- When speed matters more than precision
- The cost of delay vs. the cost of error
- Real-time decision-making in operations
- Information latency cascades

