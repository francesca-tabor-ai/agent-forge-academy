## Role Play

### Present a Model Recommendation to an Ops Lead and Handle Pushback

**Scenario:** You've built a demand forecasting model and need to get operations to use it

**Setting:**
- You: Data scientist/AI engineer
- Ops Lead: Plant manager or supply chain director
- Context: Current forecasting is manual, time-consuming, and often inaccurate

**Your Presentation Should Include:**
1. **Problem Statement**
   - What problem are you solving?
   - Why it matters to operations
   - Current pain points

2. **Solution Overview**
   - What the model does (in plain language)
   - How it helps operations
   - Key benefits

3. **How It Works**
   - Simple explanation (no technical jargon)
   - What inputs it needs
   - What outputs it provides
   - How operations will use it

4. **Constraints Respected**
   - Physical constraints (capacity, lead times)
   - Economic constraints (costs, budgets)
   - Human constraints (overrides, exceptions)

5. **Implementation Plan**
   - How it integrates with current processes
   - Training and support
   - Rollout approach
   - Success metrics

**Expected Pushback:**
- "This won't work because..."
- "We tried something like this before..."
- "What if [edge case] happens?"
- "How do we override it?"
- "What if the data is wrong?"

**Your Response Strategy:**
- Listen and understand concerns
- Acknowledge valid points
- Address constraints and edge cases
- Show flexibility and willingness to adapt
- Build trust through transparency

**Learning Objectives:**
- Practice explaining technical concepts simply
- Handle objections constructively
- Build credibility and trust
- Understand operations perspective
- Design for real-world use

