## Practical Exercise

### Interview an Operations Professional

**Objective:** Understand operations perspective firsthand

**Activity:**

1. **Find an Operations Contact**
   - Planner, buyer, plant manager, or similar
   - Someone willing to share their perspective

2. **Prepare Questions**
   - About their daily challenges
   - About data and systems they use
   - About what would help them
   - About past experiences with AI/ML

3. **Conduct Interview**
   - Listen more than talk
   - Ask follow-up questions
   - Understand their language
   - Note pain points and priorities

4. **Synthesize Learnings**
   - Key insights
   - Language and terminology
   - Priorities and concerns
   - How to better communicate

**Deliverables:**
- Interview notes
- Key insights document
- Communication recommendations
- Questions to use in future

