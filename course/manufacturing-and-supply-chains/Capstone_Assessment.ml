# Capstone Project: Operations-Aware AI Design

**Problem:** Designing AI models without understanding operational reality  
**Capability:** End-to-End Operations-Aware AI Design  
**Inspiration:** Real-world AI deployments in manufacturing and supply chains

---

## Project Overview

Apply everything you've learned to design an AI solution for a real operational decision. This capstone integrates all course modules and demonstrates your ability to design models that respect physical, economic, and human constraints.

---

## Project Structure

### Phase 1: Problem Selection and System Understanding (Week 1)

**Choose a Real Operational Decision:**
- Demand forecasting
- Inventory optimization
- Production scheduling
- Supplier selection and management
- Capacity planning
- Route optimization
- Quality prediction
- Maintenance scheduling

**System Mapping:**
- Map the complete operational system
- Identify all stages and dependencies
- Document material, information, and money flows
- Identify constraints (physical, economic, human)
- Map feedback loops

**Deliverable:** System map and problem statement

---

### Phase 2: Constraint and Data Analysis (Week 2)

**Physical Constraints:**
- Capacity limits
- Lead times (fixed vs. variable)
- Geographic constraints
- Bottlenecks and critical paths

**Economic Constraints:**
- Costs and budgets
- Working capital
- Payment terms
- Trade-offs between objectives

**Human Constraints:**
- Decision-maker preferences
- Override requirements
- Exception handling
- Change management needs

**Data Assessment:**
- Data availability and quality
- Timeliness and delays
- Manual overrides and shadow systems
- Aggregation issues
- What data is missing

**Deliverable:** Constraint analysis and data quality assessment

---

### Phase 3: Model Design (Week 3)

**Model Specification:**
- What will the model predict/optimize?
- What inputs are needed?
- What outputs will be provided?
- How will it integrate with existing processes?

**Constraint Integration:**
- How will the model respect physical constraints?
- How will it handle economic constraints?
- How will it support human overrides?
- What feedback loops will it account for?

**Uncertainty Handling:**
- How will the model handle uncertainty?
- What safety buffers are needed?
- How will it adapt to changes?
- What monitoring is required?

**Deliverable:** Model design document

---

### Phase 4: Communication and Implementation Plan (Week 4)

**Stakeholder Communication:**
- How will you explain the model to operations?
- What language will you use?
- How will you handle objections?
- What questions will you ask?

**Implementation Strategy:**
- Rollout plan
- Training requirements
- Integration with existing systems
- Change management approach

**Success Metrics:**
- How will you measure success?
- What business outcomes matter?
- How will you monitor the model?
- When will you know it's working?

**Deliverable:** Communication plan and implementation strategy

