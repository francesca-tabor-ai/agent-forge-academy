## Project Examples

### Example 1: Demand Forecasting for Seasonal Products

**System:** Retail supply chain with seasonal demand patterns

**Challenges:**
- High demand variability
- Long lead times
- Promotional impacts
- Supplier reliability

**Model Design:**
- Forecast with uncertainty quantification
- Account for promotions and seasonality
- Respect lead time constraints
- Allow planner overrides

### Example 2: Production Scheduling with Capacity Constraints

**System:** Manufacturing line with multiple products and shared resources

**Challenges:**
- Capacity bottlenecks
- Setup times
- Material availability
- Quality issues

**Model Design:**
- Optimize for throughput, not utilization
- Respect capacity constraints
- Account for setup times
- Allow scheduler overrides

### Example 3: Inventory Optimization with Supplier Risk

**System:** Multi-echelon inventory with unreliable suppliers

**Challenges:**
- Supplier lead time variability
- Demand uncertainty
- Service level requirements
- Working capital constraints

**Model Design:**
- Optimize inventory with supplier risk
- Balance service level and cost
- Account for lead time variability
- Respect working capital limits

