## Key Concepts

### Bills of Materials (BOMs)

- Hierarchical product structure
- Parent-child relationships
- Multi-level complexity
- Common components
- BOM accuracy and maintenance

### Component Dependencies

- Dependent demand (driven by parent)
- Independent demand (end customer)
- Commonality across products
- Critical path through BOM
- Dependency risk

### Lead Time Types

- **Fixed:** Deterministic, predictable
- **Variable:** Stochastic, uncertain
- **Structural:** Cannot be changed
- **Controllable:** Can be influenced
- **Safety lead time:** Buffer for uncertainty

### Supplier Reliability

- Average lead time vs. actual lead time
- Lead time variability (standard deviation)
- On-time delivery percentage
- Common failure modes
- Risk assessment and mitigation

