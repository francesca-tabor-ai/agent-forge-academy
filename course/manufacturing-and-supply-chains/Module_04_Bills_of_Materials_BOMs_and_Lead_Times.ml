## Practical Exercise

### Build a BOM for a "Simple" Product

**Objective:** Discover hidden complexity in seemingly simple products

**Challenge:**
- Choose a product that seems simple (e.g., coffee mug, t-shirt, notebook)
- Build a complete BOM going 3+ levels deep
- Identify all raw materials
- Document all manufacturing steps
- Map supplier relationships

**Discoveries to Document:**
- How many components are actually involved?
- How many suppliers?
- What's the longest lead time path?
- Where are the dependencies?
- What would break if one supplier failed?

