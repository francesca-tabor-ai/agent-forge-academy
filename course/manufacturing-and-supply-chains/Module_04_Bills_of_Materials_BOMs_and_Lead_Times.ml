## Practical Exercise

### Identify Which Lead Times Are Controllable vs Structural

**Objective:** Understand the difference between lead times you can influence and those you can't

**Activity:**

1. **Choose a Product**
   - Select a product with a multi-level BOM
   - Examples: bicycle, laptop, furniture

2. **Map the BOM**
   - Create a multi-level BOM structure
   - Identify all components and sub-assemblies
   - Document lead times for each item

3. **Categorize Lead Times**
   - **Structural:** Cannot be changed (e.g., ocean shipping time, chemical curing time)
   - **Controllable:** Can be influenced (e.g., supplier selection, production scheduling)
   - **Variable:** Depends on conditions (e.g., supplier capacity, quality issues)

4. **Identify Critical Path**
   - Find the longest path through the BOM
   - This determines total lead time
   - Identify which items are on the critical path

5. **Analyze Supplier Reliability**
   - For each supplier/component, assess:
     - Average lead time
     - Variability (standard deviation)
     - On-time delivery percentage
     - Common failure modes

**Deliverables:**
- Multi-level BOM diagram
- Lead time categorization (structural, controllable, variable)
- Critical path identification
- Supplier reliability assessment
- Recommendations for lead time reduction

