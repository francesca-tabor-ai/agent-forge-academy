-- Seed user-dependent data
-- NOTE: These tables require existing profiles, student_profiles, etc. from auth.users
-- This script provides example queries that can be run AFTER users have signed up
-- 
-- Dependencies:
-- - profiles (depends on auth.users - cannot be seeded)
-- - student_profiles (depends on profiles)
-- - recruiter_profiles (depends on profiles)
-- - portfolio_projects (depends on student_profiles)
-- - course_enrollments (depends on courses + student_profiles)
-- - questions (depends on student_profiles)
-- - answers (depends on questions + profiles)
-- - event_presentations (depends on events + student_profiles + portfolio_projects)
-- - event_attendance (depends on events + profiles)
-- - contact_requests (depends on recruiter_profiles + student_profiles)
--
-- consent_events and admin_audit_log are typically auto-generated by triggers

BEGIN;

-- Example: Seed course enrollments (requires courses + student_profiles)
-- Uncomment and modify when you have student profiles:
/*
INSERT INTO course_enrollments (course_id, student_profile_id, progress_percentage)
