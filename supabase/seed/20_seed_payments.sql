-- Example 2: Seed payments for users with stripe_customers
-- Creates payment records for users who have Stripe customers but may not have subscriptions
-- Uncomment and modify when you have users and stripe_customers:
/*
DO $$
DECLARE
  customer_record RECORD;
  payment_id_var TEXT;
  amount_var INTEGER;
  currency_var TEXT;
  status_var TEXT;
  payment_counter INTEGER;
BEGIN
  -- Loop through Stripe customers
  FOR customer_record IN 
    SELECT 
      sc.user_id,
      sc.stripe_customer_id
    FROM stripe_customers sc
    LIMIT 5
  LOOP
    -- Create 1-2 payment records per customer
    FOR payment_counter IN 1..(1 + FLOOR(RANDOM() * 1)::INTEGER) LOOP
      -- Generate payment intent ID
      payment_id_var := 'pi_' || substr(md5(random()::text || customer_record.stripe_customer_id || payment_counter::text), 1, 24);
      
