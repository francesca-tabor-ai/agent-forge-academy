-- Seed payments: Payment history ledger (invoices and payment outcomes)
-- NOTE: This table is typically populated by Stripe webhooks (invoice.paid events)
-- This script provides example payment records that demonstrate the structure
-- NOTE: Payments require existing auth.users (user_id) and optionally subscriptions
--
-- NOTE: This script should be run using a direct database connection (psql)
-- which bypasses Row Level Security (RLS). The connection string should be
-- the "Direct connection" or "Transaction pooler" from Supabase Dashboard.

BEGIN;

-- Dependencies:
-- - auth.users (created via authentication)
-- - stripe_customers (optional - for stripe_customer_id references)
-- - subscriptions (optional - for stripe_subscription_id references)
-- - payments (depends on auth.users)

-- IMPORTANT: 
-- - Payments are typically auto-generated by Stripe webhooks (invoice.paid events)
-- - Payment IDs are Stripe payment_intent IDs (pi_...) or charge IDs (ch_...)
-- - Amount is stored in smallest currency unit (e.g., 3900 = £39.00 or $39.00)
-- - Currency codes: 'gbp', 'usd', 'eur', etc.
-- - Status values: 'succeeded', 'failed', 'pending', 'refunded'
-- - For seed data, we use example Stripe IDs (pi_... format)

-- Example 1: Seed payments for users with subscriptions
